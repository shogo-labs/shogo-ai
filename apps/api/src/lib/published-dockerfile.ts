/**
 * The one Dockerfile a published image is built from (SHO-308 §2).
 *
 * It lives here rather than in the app's repo because it is platform
 * infrastructure: an app can edit its own `Dockerfile` and the build must not
 * change behaviour. The BuildKit Job writes this file into the build context
 * before it runs, so the recipe and the Job that consumes it cannot drift.
 *
 * What it deliberately does NOT do:
 *   - `vite build` / `expo export` — the artifact tarball already carries the
 *     root-based `dist/` produced by the editing runtime, because a published
 *     bundle must not be path-prefixed like the canvas preview.
 *   - read git — the context already is the commit.
 *   - install at boot.
 *
 * `SHOGO_PREBUILT_IMAGE=true` is what tells the runtime at boot that deps,
 * the generated Prisma client and `dist/` are baked in, so it only has to
 * start `server.tsx` (see `preview-manager.ts` / `initializePublished`).
 */
export const PUBLISHED_DOCKERFILE_NAME = 'Dockerfile.published'

export function publishedDockerfile(): string {
  return [
    '# Generated by apps/api/src/lib/published-dockerfile.ts — do not edit in a project.',
    'FROM oven/bun:1.1-slim',
    '',
    'WORKDIR /app',
    'ENV NODE_ENV=production',
    'ENV SHOGO_PREBUILT_IMAGE=true',
    '',
    '# The build context is the commit: source + package manifests + the',
    '# root-based dist/ the editing runtime produced for publishing.',
    'COPY . /app',
    '',
    '# Dependencies are resolved once, here, so a published pod never installs.',
    '# A missing lockfile is normal for a template app, hence the fallback.',
    'RUN if [ -f bun.lockb ] || [ -f bun.lock ]; then bun install --production --frozen-lockfile; else bun install --production; fi',
    '',
    '# The generated Prisma client is part of the image, so boot never runs',
    "# prisma generate. Prefer the app's own CLI so the build stays offline-capable.",
    'RUN if [ -f prisma/schema.prisma ]; then if [ -x node_modules/.bin/prisma ]; then node_modules/.bin/prisma generate --schema prisma/schema.prisma; else bunx prisma generate --schema prisma/schema.prisma; fi; fi',
    '',
    'ENV PORT=3000',
    'EXPOSE 3000',
    '',
    '# The runtime writes its logs under /app, so the non-root user must own it,',
    '# and nothing in a published pod needs to be privileged.',
    'RUN chown -R bun:bun /app',
    'USER bun',
    'CMD ["bun", "server.tsx"]',
    '',
  ].join('\n')
}
