/**
 * The project-bucket CDN path contract (SHO-491).
 *
 * Public objects are served at
 *
 *   `https://cdn.<publish domain>/<projectId>/<key>`
 *
 * and that URL is rewritten to the object's storage key
 *
 *   `p/<projectId>/public/<key>`
 *
 * The rewrite is the security boundary: the read-only pre-authenticated request
 * the CDN uses covers the WHOLE bucket, so a private object is safe only because
 * the rewrite refuses to build a path outside `public/`.
 *
 * The Worker that enforces it at the edge is generated by Terraform
 * (`terraform/modules/publish-hosting-oci`), which cannot import this file, so
 * the function is duplicated there. **This implementation is the executable
 * spec** — `apps/api/src/__tests__/project-bucket-cdn.test.ts` evaluates the
 * Worker's copy out of the Terraform source and fails if the two disagree.
 */

import { BUCKET_PREFIX, type BucketVisibility } from './project-bucket-keys'

/** Ids are opaque and never contain a dot or a slash. */
const PROJECT_ID_PATTERN = /^[A-Za-z0-9_-]{1,64}$/

/**
 * Storage key a public CDN path names, or `null` when the path is not a valid
 * `<projectId>/<key>` pair. `null` is a 404 at the edge, never a fallthrough.
 */
export function cdnObjectKey(pathname: string): string | null {
  const trimmed = pathname.replace(/^\/+/, '')
  if (!trimmed) return null
  const slash = trimmed.indexOf('/')
  if (slash <= 0) return null
  const projectId = trimmed.slice(0, slash)
  const rest = trimmed.slice(slash + 1)
  if (!rest) return null
  if (!PROJECT_ID_PATTERN.test(projectId)) return null
  const segments = rest.split('/')
  for (const segment of segments) {
    if (!segment || segment === '.' || segment === '..') return null
  }
  return publicObjectStorageKey(projectId, rest)
}

/** `p/<projectId>/public/<key>` — the only layout the CDN may read. */
export function publicObjectStorageKey(projectId: string, key: string): string {
  return `${BUCKET_PREFIX}${projectId}/${'public' satisfies BucketVisibility}/${key}`
}

/**
 * Whether a key is content-addressed, and so safe to cache for a year. A caller
 * that keeps writing the same key gets a short max-age instead.
 */
export function cdnCacheControl(key: string): string {
  const name = key.slice(key.lastIndexOf('/') + 1)
  const immutable = /^[0-9a-f]{16}(-|\.|$)/.test(name) || /^[0-9a-f]{64}(\.|$)/.test(name)
  return immutable ? 'public, max-age=31536000, immutable' : 'public, max-age=300'
}
