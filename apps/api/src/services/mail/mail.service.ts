const DECISION_CATEGORY: Record<string, string> = { allow: 'important', block: 'spam', feed: 'feed', paper_trail: 'paper_trail' }

export async function decideSender(mailboxId: string, userId: string, input: { address?: unknown; decision?: unknown }) {
  await mailboxForUser(mailboxId, userId, { write: true })
  const address = typeof input.address === 'string' ? normalizeAddress(input.address) : ''
  const decision = typeof input.decision === 'string' ? input.decision : ''
  if (!address || !DECISION_CATEGORY[decision]) throw new MailError(400, 'invalid_decision', 'decision must be allow, block, feed or paper_trail')
  const sender = await db.mailSender.upsert({
    where: { mailboxId_address: { mailboxId, address } },
    create: { mailboxId, address, decision, decidedByUserId: userId },
    update: { decision, decidedByUserId: userId },
  })
  // Everything this sender already has waiting in the Screener moves with the decision.
  const theirs = await db.mailMessage.findMany({ where: { mailboxId, fromAddress: address, threadId: { not: null } }, select: { threadId: true } })
  const threadIds = [...new Set(theirs.map((m: any) => m.threadId))]
  if (threadIds.length) {
    await db.mailThread.updateMany({ where: { id: { in: threadIds }, category: 'screener' }, data: { category: DECISION_CATEGORY[decision] } })
  }
  return { address: sender.address, decision: sender.decision }
}

function ruleInput(body: Record<string, any>) {
  const match: RuleMatch = {}
  const m = body.match && typeof body.match === 'object' ? body.match : {}
  for (const k of ['from', 'fromDomain', 'to', 'subject', 'body'] as const) {
    const v = m[k] ?? (k === 'subject' ? m.subjectContains : k === 'body' ? m.bodyContains : undefined)
    if (typeof v === 'string' && v.trim()) match[k] = v.trim().slice(0, 200)
  }
  if (typeof m.hasAttachment === 'boolean') match.hasAttachment = m.hasAttachment
  if (typeof m.bulk === 'boolean') match.bulk = m.bulk
  const a = body.action && typeof body.action === 'object' ? body.action : {}
  const action: Record<string, unknown> = {}
  if (typeof a.category === 'string') action.category = a.category
  if (typeof (a.assigneeUserId ?? a.assignTo) === 'string') action.assigneeUserId = a.assigneeUserId ?? a.assignTo
  if (typeof a.status === 'string') action.status = a.status
  if (typeof a.agentRef === 'string') action.agentRef = a.agentRef
  return { match, action }
}

