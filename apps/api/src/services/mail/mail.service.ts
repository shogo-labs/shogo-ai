export interface InboundInput {
  raw: Uint8Array
  envelopeTo?: string[]
  auth?: { spf?: string; dkim?: string; dmarc?: string } | null
  provider: string
  providerMessageId?: string | null
  /** A synced account delivers into its own mailbox, whatever the To says. */
  mailboxId?: string
  receivedAt?: Date
  /** Skip agent wakes and notifications (an account's first backfill). */
  quiet?: boolean
  /** Only deliver to mailboxes of this workspace (the home region's share of a webhook). */
  workspaceId?: string
}

function addressesOf(list: Array<{ address?: string; name?: string; group?: Array<{ address: string; name: string }> }> | undefined): MailAddress[] {
  const out: MailAddress[] = []
  for (const a of list ?? []) {
    if (a.group) for (const g of a.group) out.push({ address: normalizeAddress(g.address), name: g.name || null })
    else if (a.address) out.push({ address: normalizeAddress(a.address), name: a.name || null })
  }
  return out
}

/** The mailboxes an email is for: exact addresses first, then catch-alls on the same domain. */
async function targetMailboxes(addresses: string[], workspaceId?: string) {
  const unique = [...new Set(addresses.map(normalizeAddress))]
  if (!unique.length) return []
  const scope = workspaceId ? { workspaceId } : {}
  const exact = await db.mailbox.findMany({
    where: { address: { in: unique }, archivedAt: null, domain: { status: 'active', receivingEnabled: true }, ...scope },
    include: { domain: true },
  })
  const found = new Set(exact.map((m: any) => m.address))
  const missingDomains = [...new Set(unique.filter((a) => !found.has(a)).map(domainOf))]
  const catchAll = missingDomains.length
    ? await db.mailbox.findMany({
        where: { catchAll: true, archivedAt: null, domain: { domain: { in: missingDomains }, status: 'active', receivingEnabled: true }, ...scope },
        include: { domain: true },
      })
    : []
  const byId = new Map<string, any>()
  for (const m of [...exact, ...catchAll]) byId.set(m.id, m)
  return [...byId.values()]
}

/** The workspaces an inbound email belongs to, so a webhook can hand each its share in its home region. */
export async function workspacesForInbound(input: Pick<InboundInput, 'raw' | 'envelopeTo'>): Promise<string[]> {
  const parsed = await PostalMime.parse(input.raw)
  const addresses = [...(input.envelopeTo ?? []), ...addressesOf(parsed.to as any).map((a) => a.address), ...addressesOf(parsed.cc as any).map((a) => a.address)]
  return [...new Set((await targetMailboxes(addresses)).map((m: any) => m.workspaceId as string))]
}

export async function ingestInbound(input: InboundInput): Promise<{ delivered: number; skipped: string | null }> {
  const parsed = await PostalMime.parse(input.raw)
  const headers = headerMap(parsed.headers as Array<{ key: string; value: string }>)
  const from = addressesOf(parsed.from ? [parsed.from as any] : [])[0] ?? { address: 'unknown@invalid', name: null }
  const to = addressesOf(parsed.to as any)
  const cc = addressesOf(parsed.cc as any)
  const mailboxes = input.mailboxId
    ? await db.mailbox.findMany({ where: { id: input.mailboxId, archivedAt: null }, include: { domain: true } })
    : await targetMailboxes([...(input.envelopeTo ?? []), ...to.map((a) => a.address), ...cc.map((a) => a.address)], input.workspaceId)
  if (!mailboxes.length) return { delivered: 0, skipped: 'no_mailbox' }
  let delivered = 0
  for (const mailbox of mailboxes) {
    if (await ingestInto(mailbox, input, parsed, headers, from, to, cc)) delivered++
  }
  return { delivered, skipped: delivered ? null : 'duplicate' }
}

async function ingestInto(
  mailbox: any,
  input: InboundInput,
  parsed: any,
  headers: Record<string, string>,
  from: MailAddress,
  to: MailAddress[],
  cc: MailAddress[],
): Promise<boolean> {
  const rfcMessageId = parsed.messageId?.trim() || `<${input.providerMessageId ?? crypto.randomUUID()}@inbound.shogo>`
  if (await db.mailMessage.findUnique({ where: { mailboxId_rfcMessageId: { mailboxId: mailbox.id, rfcMessageId } } })) return false
  // Our own send coming back (a BCC to ourselves, a list echo) is already in the thread.
  if (from.address === mailbox.address && await db.mailMessage.findFirst({ where: { rfcMessageId, direction: 'outbound' } })) return false

  const now = input.receivedAt ?? new Date()
  const subject = (parsed.subject ?? '').trim() || '(no subject)'
  const html = typeof parsed.html === 'string' ? parsed.html : null
  const fullText = (typeof parsed.text === 'string' && parsed.text.trim() ? parsed.text : html ? htmlToText(html) : '').trim()
  const replyToList = addressesOf(parsed.replyTo as any)
  const bulk = looksBulk(headers)
  const auto = isAutoGenerated(headers, from.address)

  // Thread: References / In-Reply-To first, then the same subject with the same person lately.
  const refs = [...parseMessageIds(parsed.inReplyTo), ...parseMessageIds(parsed.references)]
  let thread: any = null
  if (refs.length) {
    const hit = await db.mailMessage.findFirst({ where: { mailboxId: mailbox.id, rfcMessageId: { in: refs }, threadId: { not: null } }, orderBy: { createdAt: 'desc' } })
    if (hit) thread = await db.mailThread.findUnique({ where: { id: hit.threadId } })
  }
  const normalized = normalizeSubject(subject)
  if (!thread && normalized && /^(re|aw|sv)\s*:/i.test(subject)) {
    const candidates = await db.mailThread.findMany({
      where: { mailboxId: mailbox.id, normalizedSubject: normalized, lastMessageAt: { gte: new Date(now.getTime() - THREAD_SUBJECT_WINDOW_MS) } },
      orderBy: { lastMessageAt: 'desc' },
      take: 5,
    })
    thread = candidates.find((t: any) => readJson<string[]>(t.participants, []).includes(from.address)) ?? null
  }

  const sender = await db.mailSender.findUnique({ where: { mailboxId_address: { mailboxId: mailbox.id, address: from.address } } })
  const category = thread ? thread.category : categorize({ bulk, screened: mailbox.screenerEnabled, decision: sender?.decision ?? null })
  const body = thread ? stripQuotedReply(fullText) : fullText
  const chatText = (body || '(no text)').slice(0, MAX_MESSAGE_CHARS - 100)

  const mailId = crypto.randomUUID()
  const keyBase = `artifacts/mail/${mailbox.workspaceId}/${mailbox.id}/${mailId}`
  const rawStorageKey = `${keyBase}.eml`
  await putConversationFile(rawStorageKey, input.raw, 'message/rfc822')
  let htmlStorageKey: string | null = null
  if (html && html.length <= MAX_HTML_BYTES) {
    htmlStorageKey = `${keyBase}.html`
    await putConversationFile(htmlStorageKey, new TextEncoder().encode(html), 'text/html')
  }

  const draft = {
    id: mailId,
    workspaceId: mailbox.workspaceId,
    mailboxId: mailbox.id,
    threadId: thread?.id ?? null,
    direction: 'inbound',
    status: 'received',
    rfcMessageId,
    inReplyTo: parsed.inReplyTo?.trim() || null,
    references: parsed.references?.trim() || null,
    fromAddress: from.address,
    fromName: from.name ?? null,
    toList: JSON.stringify(to),
    ccList: JSON.stringify(cc),
    bccList: '[]',
    replyTo: replyToList.length ? replyToList.map((a) => a.address).join(', ') : null,
    subject,
    snippet: snippetOf(body || fullText),
    textBody: fullText.slice(0, 200_000),
    htmlStorageKey,
    rawStorageKey,
    authResults: input.auth ? JSON.stringify(input.auth) : null,
    spamVerdict: category === 'spam' ? 'blocked_sender' : null,
    attachmentMeta: '[]',
    provider: input.provider,
    providerMessageId: input.providerMessageId ?? null,
    receivedAt: now,
    createdAt: now,
  }

  const posted = await postMessage({
    conversationId: mailbox.conversationId,
    text: chatText,
    authorType: 'bot',
    threadRootId: thread?.rootMessageId ?? null,
    blocks: { email: emailBlockFor(draft) },
    skipMentions: true,
    externalRef: `mail:${mailbox.id}:${rfcMessageId}`.slice(0, 500),
    createdAt: now,
  })
  if (posted.duplicate) return false

  const attachments: MailAttachmentMeta[] = []
  for (const a of (parsed.attachments ?? []).slice(0, MAX_INBOUND_ATTACHMENTS)) {
    if (a.disposition === 'inline' && a.contentId && html?.includes(`cid:${a.contentId.replace(/[<>]/g, '')}`)) continue
    const bytes = typeof a.content === 'string' ? new TextEncoder().encode(a.content) : new Uint8Array(a.content as ArrayBuffer)
    if (!bytes.byteLength) continue
    const name = (a.filename || 'attachment').slice(0, 255)
    const key = buildConversationFileKey(mailbox.workspaceId, mailbox.conversationId, name)
    await putConversationFile(key, bytes, a.mimeType || 'application/octet-stream')
    const att = await db.conversationAttachment.create({
      data: {
        conversationId: mailbox.conversationId,
        messageId: posted.row.id,
        uploaderAgentRef: 'mail',
        storageKey: key,
        name,
        mimeType: a.mimeType || 'application/octet-stream',
        size: bytes.byteLength,
      },
    })
    attachments.push({ name, mimeType: att.mimeType, size: att.size, attachmentId: att.id })
  }
  if (attachments.length) await refreshAttachmentPreview(posted.row.id).catch(() => {})

  const slaDueAt = mailbox.slaHours && !bulk ? new Date(now.getTime() + mailbox.slaHours * 60 * 60_000) : null
  if (!thread) {
    thread = await db.mailThread.create({
      data: {
        workspaceId: mailbox.workspaceId,
        mailboxId: mailbox.id,
        rootMessageId: posted.row.id,
        subject,
        normalizedSubject: normalized,
        participants: JSON.stringify([...new Set([from.address, ...to.map((a) => a.address), ...cc.map((a) => a.address)])].filter((a) => a !== mailbox.address)),
        category,
        status: 'open',
        slaDueAt,
        lastInboundAt: now,
        lastMessageAt: now,
        messageCount: 1,
      },
    })
  } else {
    const participants = new Set(readJson<string[]>(thread.participants, []))
    participants.add(from.address)
    thread = await db.mailThread.update({
      where: { id: thread.id },
      data: {
        participants: JSON.stringify([...participants]),
        // A reply brings a thread back: reopened, unsnoozed, on the clock again.
        status: 'open',
        snoozedUntil: null,
        slaDueAt: slaDueAt ?? thread.slaDueAt,
        lastInboundAt: now,
        lastMessageAt: now,
        messageCount: { increment: 1 },
      },
    })
  }

  const row = await db.mailMessage.create({
    data: { ...draft, threadId: thread.id, conversationMessageId: posted.row.id, attachmentMeta: JSON.stringify(attachments) },
  })
  await syncBlock(row.id)

  const ruled = await applyRules(mailbox, thread, row, { bulk, hasAttachment: attachments.length > 0, isNewThread: thread.messageCount === 1 })
  thread = ruled.thread
  const visible = thread.category === 'important' || thread.category === 'feed'
  if (!input.quiet && visible) {
    void afterMessagePosted(posted, { actorUserId: null, origin: 'bot' })
    const wantsAgent = (mailbox.kind === 'agent' && mailbox.agentRef) || ruled.agentRefs.length > 0
    if (!auto && !bulk && thread.category === 'important' && wantsAgent) {
      const blocked = await agentWakeBlocked(mailbox, row, input.auth ?? null, now)
      if (blocked) console.warn(`[Mail] not waking agents for ${mailbox.address}: ${blocked}`)
      else await wakeAgents(mailbox, posted, thread, ruled.agentRefs)
    }
  }
  return true
}

/** Inbound mail that may wake an agent per sender per hour, and per mailbox per day. */
export const AGENT_WAKES_PER_SENDER_PER_HOUR = 5
export const AGENT_WAKES_PER_MAILBOX_PER_DAY = 200

/**
 * Anyone on the internet can write to an agent's address, and every wake is an
 * agent run the workspace pays for. Mail that failed DMARC (a forged sender)
 * never wakes one, and a sender or mailbox over its budget waits for a person.
 * The email itself is still delivered to the mailbox either way.
 */
async function agentWakeBlocked(mailbox: any, mail: any, auth: { dmarc?: string } | null, now: Date): Promise<string | null> {
  if (auth?.dmarc && /^fail/i.test(auth.dmarc)) return 'sender failed DMARC'
  const bySender = await db.mailMessage.count({
    where: { mailboxId: mailbox.id, direction: 'inbound', fromAddress: mail.fromAddress, createdAt: { gte: new Date(now.getTime() - 60 * 60_000) } },
  })
  if (bySender > AGENT_WAKES_PER_SENDER_PER_HOUR) return `over ${AGENT_WAKES_PER_SENDER_PER_HOUR} emails an hour from ${mail.fromAddress}`
  const byMailbox = await db.mailMessage.count({
    where: { mailboxId: mailbox.id, direction: 'inbound', createdAt: { gte: new Date(now.getTime() - 24 * 60 * 60_000) } },
  })
  if (byMailbox > AGENT_WAKES_PER_MAILBOX_PER_DAY) return `over ${AGENT_WAKES_PER_MAILBOX_PER_DAY} emails a day`
  return null
}

async function applyRules(mailbox: any, thread: any, mail: any, ctx: { bulk: boolean; hasAttachment: boolean; isNewThread: boolean }) {
  const rules = await db.mailRule.findMany({ where: { mailboxId: mailbox.id, enabled: true }, orderBy: { position: 'asc' } })
  const agentRefs: string[] = []
  if (!rules.length) return { thread, agentRefs }
  const subject = {
    from: mail.fromAddress,
    to: [...readAddressJson(mail.toList), ...readAddressJson(mail.ccList)].map((a) => a.address),
    subject: mail.subject,
    body: mail.textBody ?? '',
    hasAttachment: ctx.hasAttachment,
    bulk: ctx.bulk,
  }
  const data: Record<string, unknown> = {}
  for (const rule of rules) {
    if (!ruleMatches(readJson<RuleMatch>(rule.match, {}), subject)) continue
    const action = readJson<Record<string, any>>(rule.action, {})
    // Moving a whole thread is for its first message; later replies follow the thread.
    if (ctx.isNewThread && typeof action.category === 'string' && ['important', 'feed', 'paper_trail', 'spam'].includes(action.category)) data.category = action.category
    const assignee = action.assigneeUserId ?? action.assignTo
    if (typeof assignee === 'string' && assignee) {
      const member = await db.conversationMember.findFirst({ where: { conversationId: mailbox.conversationId, userId: assignee } })
      if (member) data.assigneeUserId = assignee
    }
    if (action.status === 'done' || action.markDone === true) data.status = 'done'
    else if (action.status === 'open' || action.status === 'waiting') data.status = action.status
    if (typeof action.agentRef === 'string' && action.agentRef) agentRefs.push(action.agentRef)
  }
  if (!Object.keys(data).length) return { thread, agentRefs }
  return { thread: await db.mailThread.update({ where: { id: thread.id }, data }), agentRefs }
}

/** Wake the mailbox's agent (and any a rule names) on a new email; it answers in the thread. */
async function wakeAgents(mailbox: any, posted: any, thread: any, extraRefs: string[]) {
  const refs = new Set<string>(extraRefs)
  if (mailbox.kind === 'agent' && mailbox.agentRef) refs.add(mailbox.agentRef)
  if (!refs.size) return
  const userId = mailbox.ownerUserId ?? (await db.member.findFirst({
    where: { workspaceId: mailbox.workspaceId, projectId: null, role: 'owner' },
    select: { userId: true },
  }))?.userId
  if (!userId) return
  const { runAgentReply } = await import('../conversation-agent-dispatcher')
  for (const ref of refs) {
    const projectId = ref === 'workspace' ? null : ref.replace(/^project:/, '')
    const member = await db.conversationMember.findFirst({ where: { conversationId: mailbox.conversationId, memberType: 'agent', projectId } })
    if (!member || member.agentMuted) continue
    void runAgentReply({
      conversation: posted.conversation,
      trigger: posted.row,
      target: { projectId },
      userId,
      threadRootId: thread.rootMessageId,
    }).catch((err) => console.error('[Mail] agent wake failed:', err))
  }
}

