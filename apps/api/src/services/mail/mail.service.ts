export function serializeDomain(row: any) {
  return {
    id: row.id,
    domain: row.domain,
    mode: row.mode,
    status: row.status,
    provider: row.provider,
    records: readJson<any[]>(row.records, []),
    sendingEnabled: row.sendingEnabled,
    receivingEnabled: row.receivingEnabled,
    verifiedAt: row.verifiedAt ?? null,
    lastCheckedAt: row.lastCheckedAt ?? null,
    lastError: row.lastError ?? null,
    sendingPaused: !!row.sendingPausedAt,
    pausedAt: row.sendingPausedAt ?? null,
    pausedReason: row.pauseReason ?? null,
  }
}

