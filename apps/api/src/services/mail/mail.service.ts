export interface OutboundInput {
  to?: unknown
  cc?: unknown
  bcc?: unknown
  subject?: unknown
  text?: unknown
  attachmentIds?: unknown
  sendAt?: unknown
  replyAll?: unknown
}

function recipients(input: OutboundInput) {
  const to = parseAddressList(input.to)
  const cc = parseAddressList(input.cc)
  const bcc = parseAddressList(input.bcc)
  const invalid = [...to.invalid, ...cc.invalid, ...bcc.invalid]
  if (invalid.length) throw new MailError(400, 'invalid_recipient', `Not an email address: ${invalid.slice(0, 3).join(', ')}`)
  return { to: to.addresses, cc: cc.addresses, bcc: bcc.addresses }
}

function sendAtFrom(value: unknown): Date | null {
  if (typeof value !== 'string' || !value) return null
  const at = new Date(value)
  if (Number.isNaN(at.getTime())) throw new MailError(400, 'invalid_send_at', 'sendAt must be an ISO date')
  if (at.getTime() > Date.now() + 365 * 24 * 60 * 60_000) throw new MailError(400, 'invalid_send_at', 'Schedule within a year')
  return at
}

function withSignature(text: string, signature: string | null | undefined): string {
  return signature?.trim() ? `${text.trimEnd()}\n\n-- \n${signature.trim()}` : text
}

interface QueueArgs {
  mailbox: any
  actor: MailActor
  to: MailAddress[]
  cc: MailAddress[]
  bcc: MailAddress[]
  subject: string
  text: string
  attachmentIds: string[]
  sendAt: Date | null
  thread: any | null
  parent: any | null
}

async function queueOutbound(args: QueueArgs) {
  const { mailbox, actor } = args
  if (mailbox.archivedAt) throw new MailError(403, 'archived', 'This mailbox is archived')
  const total = args.to.length + args.cc.length + args.bcc.length
  if (!total) throw new MailError(400, 'no_recipients', 'Add at least one recipient')
  const limits = await limitsFor(mailbox.workspaceId)
  if (total > limits.recipientsPerMessage) {
    throw new MailError(400, 'too_many_recipients', `One email can go to at most ${limits.recipientsPerMessage} recipients`)
  }
  const body = args.text.trim()
  if (!body) throw new MailError(400, 'empty', 'The email is empty')
  if (body.length > MAX_MESSAGE_CHARS - 2_100) throw new MailError(413, 'too_long', 'The email is too long')
  const subject = args.subject.trim().slice(0, 998) || '(no subject)'
  if (!limits.canSend) throw new MailError(402, 'paid_plan_required', PAID_PLAN_REQUIRED_MESSAGE)
  if (actor.kind === 'user') {
    await assertSenderVerified(actor.userId)
    await assertWithinDailyLimit(mailbox.workspaceId, total)
  }

  // v1: every agent email waits for a person; people get an undo window.
  const agentWrote = actor.kind === 'agent'
  const status: MailStatus = agentWrote ? 'pending_approval' : 'scheduled'
  const sendAfter = agentWrote ? null : (args.sendAt ?? new Date(Date.now() + UNDO_SEND_SECONDS * 1000))
  const text = withSignature(body, mailbox.signature)

  const mailId = crypto.randomUUID()
  const rfcMessageId = newMessageId(mailbox.domain.domain)
  const now = new Date()
  const draft = {
    id: mailId,
    workspaceId: mailbox.workspaceId,
    mailboxId: mailbox.id,
    threadId: args.thread?.id ?? null,
    direction: 'outbound',
    status,
    rfcMessageId,
    inReplyTo: args.parent?.rfcMessageId ?? null,
    references: args.parent ? replyReferences(args.parent) : null,
    fromAddress: mailbox.address,
    fromName: mailbox.displayName ?? null,
    toList: JSON.stringify(args.to),
    ccList: JSON.stringify(args.cc),
    bccList: JSON.stringify(args.bcc),
    subject,
    snippet: snippetOf(body),
    textBody: text,
    attachmentMeta: '[]',
    draftedByAgentRef: actor.kind === 'agent' ? agentRefFor(actor.projectId) : null,
    sentByUserId: actor.kind === 'user' ? actor.userId : null,
    sendAfter,
    createdAt: now,
  }

  const author = actor.kind === 'user'
    ? { authorType: 'user' as const, authorUserId: actor.userId }
    : {
        authorType: 'agent' as const,
        authorAgentRef: { projectId: actor.projectId, name: await agentDisplayName(mailbox.workspaceId, actor.projectId) },
      }
  const posted = await postMessage({
    conversationId: mailbox.conversationId,
    text,
    ...author,
    threadRootId: args.thread?.rootMessageId ?? null,
    attachmentIds: actor.kind === 'user' ? args.attachmentIds : [],
    blocks: { email: emailBlockFor(draft) },
    skipMentions: true,
    createdAt: now,
  })

  const attachments = (posted.row.attachments ?? []).map((a: any) => ({ name: a.name, mimeType: a.mimeType, size: a.size, attachmentId: a.id }))
  const attachmentBytes = attachments.reduce((n: number, a: any) => n + (a.size ?? 0), 0)
  if (attachmentBytes > limits.attachmentBytes) {
    await updateMessageInternal(posted.row.id, { deletedAt: new Date() }).catch(() => {})
    throw new MailError(413, 'attachments_too_large', `Attachments are limited to ${Math.round(limits.attachmentBytes / 1024 / 1024)} MB per email`)
  }

  let thread = args.thread
  if (!thread) {
    thread = await db.mailThread.create({
      data: {
        workspaceId: mailbox.workspaceId,
        mailboxId: mailbox.id,
        rootMessageId: posted.row.id,
        subject,
        normalizedSubject: normalizeSubject(subject),
        participants: JSON.stringify([...args.to, ...args.cc].map((a) => a.address)),
        category: 'important',
        status: 'waiting',
        lastMessageAt: now,
        messageCount: 1,
      },
    })
  } else {
    const participants = new Set(readJson<string[]>(thread.participants, []))
    for (const a of [...args.to, ...args.cc]) participants.add(a.address)
    thread = await db.mailThread.update({
      where: { id: thread.id },
      data: { participants: JSON.stringify([...participants]), lastMessageAt: now, messageCount: { increment: 1 } },
    })
  }

  const row = await db.mailMessage.create({
    data: { ...draft, threadId: thread.id, conversationMessageId: posted.row.id, attachmentMeta: JSON.stringify(attachments) },
  })
  await syncBlock(row.id)
  // People only: a person's email is a human post, so its hooks (unread, push) run.
  if (actor.kind === 'user') void afterMessagePosted({ ...posted, mentions: [] }, { actorUserId: null, origin: 'system' })
  return { mail: serializeMail(row), thread: serializeThread(thread, { conversationId: mailbox.conversationId }) }
}

export async function compose(mailboxId: string, actor: MailActor, input: OutboundInput) {
  const mailbox = actor.kind === 'user'
    ? (await mailboxForUser(mailboxId, actor.userId, { write: true })).mailbox
    : await db.mailbox.findUnique({ where: { id: mailboxId }, include: { domain: true } })
  if (!mailbox) throw notFound()
  const { to, cc, bcc } = recipients(input)
  return queueOutbound({
    mailbox,
    actor,
    to,
    cc,
    bcc,
    subject: typeof input.subject === 'string' ? input.subject : '',
    text: typeof input.text === 'string' ? input.text : '',
    attachmentIds: Array.isArray(input.attachmentIds) ? input.attachmentIds.filter((v): v is string => typeof v === 'string').slice(0, 20) : [],
    sendAt: sendAtFrom(input.sendAt),
    thread: null,
    parent: null,
  })
}

/** Default recipients for a reply: the last inbound sender (Reply-To first), plus everyone else on reply-all. */
function replyRecipients(mailbox: any, messages: any[], replyAll: boolean) {
  const own = new Set([mailbox.address])
  const lastInbound = [...messages].reverse().find((m) => m.direction === 'inbound')
  const last = lastInbound ?? messages[messages.length - 1]
  if (!last) return { to: [] as MailAddress[], cc: [] as MailAddress[], parent: null }
  let to: MailAddress[]
  if (last.direction === 'inbound') {
    const replyTo = last.replyTo ? parseAddressList(last.replyTo).addresses : []
    to = replyTo.length ? replyTo : [{ address: last.fromAddress, name: last.fromName ?? null }]
  } else {
    to = readAddressJson(last.toList)
  }
  let cc: MailAddress[] = []
  if (replyAll) {
    const seen = new Set([...own, ...to.map((a) => a.address)])
    for (const a of [...readAddressJson(last.toList), ...readAddressJson(last.ccList)]) {
      if (seen.has(a.address)) continue
      seen.add(a.address)
      cc.push(a)
    }
  }
  to = to.filter((a) => !own.has(a.address))
  cc = cc.filter((a) => !own.has(a.address))
  const parent = messages[messages.length - 1] ?? null
  return { to, cc, parent }
}

async function replyIn(thread: any, mailbox: any, actor: MailActor, input: OutboundInput) {
  const messages = await db.mailMessage.findMany({
    where: { threadId: thread.id, status: { notIn: ['cancelled', 'draft', 'pending_approval'] } },
    orderBy: { createdAt: 'asc' },
  })
  const defaults = replyRecipients(mailbox, messages, input.replyAll === true || input.replyAll === 'true')
  const explicit = recipients(input)
  const to = input.to !== undefined ? explicit.to : defaults.to
  const cc = input.cc !== undefined ? explicit.cc : defaults.cc
  return queueOutbound({
    mailbox,
    actor,
    to,
    cc,
    bcc: explicit.bcc,
    subject: typeof input.subject === 'string' && input.subject.trim() ? input.subject : replySubject(thread.subject),
    text: typeof input.text === 'string' ? input.text : '',
    attachmentIds: Array.isArray(input.attachmentIds) ? input.attachmentIds.filter((v): v is string => typeof v === 'string').slice(0, 20) : [],
    sendAt: sendAtFrom(input.sendAt),
    thread,
    parent: defaults.parent,
  })
}

