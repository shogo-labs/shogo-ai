/** Send one claimed (`sending`) email. Never throws; the row records how it went. */
async function deliver(mail: any): Promise<void> {
  const mailbox = await db.mailbox.findUnique({ where: { id: mail.mailboxId }, include: { domain: true, accounts: true } })
  const fail = (error: string) => syncBlock(mail.id, { status: 'failed', error: error.slice(0, 500) })
  if (!mailbox || mailbox.archivedAt) return void (await fail('The mailbox was archived'))
  if (mailbox.domain.sendingPausedAt) return void (await fail(`Sending is paused on ${mailbox.domain.domain}: ${mailbox.domain.pauseReason ?? 'see Settings → Mail'}`))
  if (!mailbox.domain.sendingEnabled || mailbox.domain.status !== 'active') return void (await fail(`${mailbox.domain.domain} is not verified for sending`))

  const suppressed = new Set(
    (await db.mailSuppression.findMany({ where: { workspaceId: mail.workspaceId }, select: { address: true } })).map((s: any) => s.address),
  )
  const keep = (list: MailAddress[]) => list.filter((a) => !suppressed.has(a.address))
  const to = keep(readAddressJson(mail.toList))
  const cc = keep(readAddressJson(mail.ccList))
  const bcc = keep(readAddressJson(mail.bccList))
  if (!to.length && !cc.length && !bcc.length) return void (await fail('Every recipient bounced or complained before; nothing was sent'))
  try {
    await assertWithinDailyLimit(mail.workspaceId, to.length + cc.length + bcc.length, mail.id)
  } catch (err) {
    return void (await fail((err as Error).message))
  }

  const text = mail.textBody ?? ''
  const email: OutboundEmail = {
    from: { address: mailbox.address, name: mailbox.displayName ?? null },
    to,
    cc,
    bcc,
    subject: mail.subject,
    text,
    html: textToHtml(text),
    messageId: mail.rfcMessageId,
    inReplyTo: mail.inReplyTo,
    references: mail.references,
    attachments: [],
    idempotencyKey: mail.id,
  }
  try {
    email.attachments = await loadAttachments(mail)
    const account = (mailbox.accounts ?? []).find((a: any) => a.status === 'active')
    const result = account
      ? await (await import('./imap-account')).sendViaAccount(account, email)
      : await getMailProvider().send(email)
    await syncBlock(mail.id, { status: 'sent', sentAt: new Date(), providerMessageId: result.providerMessageId, provider: account ? 'smtp' : getMailProvider().name, error: null })
    if (mail.threadId) {
      await db.mailThread.updateMany({ where: { id: mail.threadId, status: 'open' }, data: { status: 'waiting', slaDueAt: null } })
    }
  } catch (err) {
    const retryable = err instanceof MailProviderError && err.retryable
    const young = Date.now() - new Date(mail.createdAt).getTime() < RETRY_GIVE_UP_MS
    if (retryable && young) {
      await syncBlock(mail.id, { status: 'scheduled', sendAfter: new Date(Date.now() + RETRY_DELAY_MS), error: (err as Error).message.slice(0, 500) })
    } else {
      await fail((err as Error).message)
    }
  }
}

/** Background: send every scheduled email whose undo window or send-later time has passed. */
export async function sendDueMail(now = new Date()): Promise<number> {
  const home = homeRegionWorkspaceWhere()
  const due = await db.mailMessage.findMany({
    where: {
      direction: 'outbound',
      status: 'scheduled',
      sendAfter: { lte: now },
      ...(home ? { mailbox: { workspace: home } } : {}),
    },
    orderBy: { sendAfter: 'asc' },
    take: SEND_BATCH,
  })
  let sent = 0
  for (const row of due) {
    const { count } = await db.mailMessage.updateMany({ where: { id: row.id, status: 'scheduled' }, data: { status: 'sending' } })
    if (!count) continue
    await deliver({ ...row, status: 'sending' })
    sent++
  }
  return sent
}

