/** The HTML to show for one email: the stored original, or ours rendered from text. */
export async function mailHtml(mail: any): Promise<string> {
  if (mail.htmlStorageKey) return new TextDecoder().decode(await loadConversationFileBytes(mail.htmlStorageKey))
  return textToHtml(mail.textBody ?? '')
}

/** The RFC 822 source: the stored original, or rebuilt from the row for mail we sent. */
export async function mailRaw(mail: any): Promise<string> {
  if (mail.rawStorageKey) return new TextDecoder().decode(await loadConversationFileBytes(mail.rawStorageKey))
  const MailComposer = (await import('nodemailer/lib/mail-composer')).default as any
  const fmt = (list: MailAddress[]) => list.map((a) => (a.name ? { name: a.name, address: a.address } : a.address))
  const composer = new MailComposer({
    from: mail.fromName ? { name: mail.fromName, address: mail.fromAddress } : mail.fromAddress,
    to: fmt(readAddressJson(mail.toList)),
    cc: fmt(readAddressJson(mail.ccList)),
    subject: mail.subject,
    text: mail.textBody ?? '',
    html: textToHtml(mail.textBody ?? ''),
    messageId: mail.rfcMessageId,
    inReplyTo: mail.inReplyTo ?? undefined,
    references: mail.references ?? undefined,
    date: mail.sentAt ?? mail.createdAt,
  })
  const buf: Buffer = await new Promise((resolve, reject) => composer.compile().build((err: Error | null, out: Buffer) => (err ? reject(err) : resolve(out))))
  return buf.toString('utf8')
}

/** Every email in a mailbox as one mbox file, oldest first. */
export async function exportMailbox(mailboxId: string, userId: string): Promise<{ filename: string; body: string }> {
  const { mailbox } = await mailboxForUser(mailboxId, userId)
  const rows = await db.mailMessage.findMany({
    where: { mailboxId, status: { in: ['received', 'sent', 'delivered', 'bounced', 'complained'] } },
    orderBy: { createdAt: 'asc' },
  })
  let body = ''
  for (const row of rows) body += mboxEntry(row.fromAddress, row.receivedAt ?? row.sentAt ?? row.createdAt, await mailRaw(row))
  return { filename: `${mailbox.address}.mbox`, body }
}

