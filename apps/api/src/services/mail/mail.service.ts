const STATUS_RANK: Record<string, number> = { sending: 0, sent: 1, delivered: 2, failed: 3, bounced: 4, complained: 5 }

export async function workspaceForProviderMessage(providerMessageId: string): Promise<string | null> {
  if (!providerMessageId) return null
  const row = await db.mailMessage.findFirst({ where: { providerMessageId }, select: { workspaceId: true } })
  return row?.workspaceId ?? null
}

export async function applyDeliveryEvent(event: DeliveryEvent): Promise<boolean> {
  if (!event.providerMessageId) return false
  const mail = await db.mailMessage.findFirst({ where: { providerMessageId: event.providerMessageId } })
  if (!mail) return false
  const next: Record<string, string> = { sent: 'sent', delivered: 'delivered', complained: 'complained', failed: 'failed' }
  let status: string | null = next[event.type] ?? null
  if (event.type === 'bounced') status = event.permanent ? 'bounced' : null
  const data: Record<string, unknown> = {}
  if (status && (STATUS_RANK[status] ?? 0) > (STATUS_RANK[mail.status] ?? 0)) data.status = status
  if (event.type === 'bounced' || event.type === 'failed' || event.type === 'delayed') {
    data.error = String(event.detail ?? (event.type === 'delayed' ? 'Delivery is delayed; the receiving server will be retried' : `Delivery ${event.type}`)).slice(0, 500)
  }
  if (Object.keys(data).length) await syncBlock(mail.id, data)

  if ((event.type === 'bounced' && event.permanent) || event.type === 'complained') {
    const reason = event.type === 'complained' ? 'complaint' : 'bounce'
    for (const address of event.recipients.map(normalizeAddress)) {
      await db.mailSuppression.upsert({
        where: { workspaceId_address: { workspaceId: mail.workspaceId, address } },
        create: { workspaceId: mail.workspaceId, address, reason },
        update: {},
      })
    }
    await checkReputation(mail.mailboxId)
  }
  return true
}

/** Pause a domain whose recent bounce or complaint rate crossed the line. */
async function checkReputation(mailboxId: string) {
  const mailbox = await db.mailbox.findUnique({ where: { id: mailboxId }, include: { domain: true } })
  if (!mailbox || mailbox.domain.sendingPausedAt) return
  const mailboxIds = (await db.mailbox.findMany({ where: { domainId: mailbox.domainId }, select: { id: true } })).map((m: any) => m.id)
  const recent = await db.mailMessage.findMany({
    where: { mailboxId: { in: mailboxIds }, direction: 'outbound', status: { in: ['sent', 'delivered', 'bounced', 'complained'] } },
    orderBy: { sentAt: 'desc' },
    take: BOUNCE_WINDOW,
    select: { status: true },
  })
  const verdict = reputationVerdict({
    sent: recent.length,
    bounced: recent.filter((r: any) => r.status === 'bounced').length,
    complained: recent.filter((r: any) => r.status === 'complained').length,
  })
  if (verdict) {
    await db.mailDomain.update({ where: { id: mailbox.domainId }, data: { sendingPausedAt: new Date(), pauseReason: verdict } })
  }
}

