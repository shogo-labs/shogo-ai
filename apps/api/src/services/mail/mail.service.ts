/** Re-publish a mail's conversation message so the email card shows its new status. */
async function syncBlock(mailId: string, data: Record<string, unknown> = {}): Promise<any> {
  const row = await db.mailMessage.update({ where: { id: mailId }, data })
  if (row.conversationMessageId) {
    const message = await db.conversationMessage.findUnique({ where: { id: row.conversationMessageId }, select: { blocks: true } })
    const blocks = message?.blocks && typeof message.blocks === 'object' ? message.blocks : {}
    await updateMessageInternal(row.conversationMessageId, { blocks: { ...blocks, email: emailBlockFor(row) } }).catch(() => {})
  }
  return row
}

// ─── Access ──────────────────────────────────────────────────────────────────

async function requireMember(workspaceId: string, userId: string) {
  const role = await getWorkspaceRole(workspaceId, userId)
  if (!role) throw new MailError(403, 'forbidden', 'No access to this workspace')
  return role
}

async function requireAdmin(workspaceId: string, userId: string) {
  const role = await requireMember(workspaceId, userId)
  if (role !== 'owner' && role !== 'admin') throw new MailError(403, 'forbidden', 'Only workspace owners and admins can manage email')
  return role
}

/** A mailbox the person can read (a member of its conversation). */
async function mailboxForUser(mailboxId: string, userId: string, opts: { write?: boolean } = {}) {
  const mailbox = await db.mailbox.findUnique({ where: { id: mailboxId }, include: { domain: true } })
  if (!mailbox) throw notFound()
  let access: ConversationAccess
  try {
    access = await loadAccess(mailbox.conversationId, userId)
  } catch {
    throw notFound()
  }
  if (opts.write && (!canPost(access, { threadReply: true }) || mailbox.archivedAt)) {
    throw new MailError(403, 'forbidden', mailbox.archivedAt ? 'This mailbox is archived' : 'You cannot send from this mailbox')
  }
  return { mailbox, access }
}

/** Mailboxes an agent may read: its own agent mailboxes, and any mailbox whose conversation it is a member of. */
async function mailboxesForAgent(workspaceId: string, projectId: string | null) {
  const memberOf = await db.conversationMember.findMany({
    where: { memberType: 'agent', projectId, conversation: { workspaceId } },
    select: { conversationId: true },
  })
  return db.mailbox.findMany({
    where: {
      workspaceId,
      archivedAt: null,
      OR: [
        { agentRef: agentRefFor(projectId) },
        { conversationId: { in: memberOf.map((m: any) => m.conversationId) } },
      ],
    },
    include: { domain: true },
    orderBy: { createdAt: 'asc' },
  })
}

async function mailboxForAgent(workspaceId: string, projectId: string | null, ref: string) {
  const all = await mailboxesForAgent(workspaceId, projectId)
  const needle = ref.trim().toLowerCase()
  const hit = all.find((m: any) => m.id === ref || m.address === needle || m.localPart === needle || m.address.split('@')[0] === needle)
  if (!hit) throw new MailError(404, 'not_found', `Mailbox "${ref}" not found, or this agent cannot use it`)
  return hit
}

/**
 * The person sending (or approving an agent's draft) must have a verified
 * email and no signup-trust hold. Local mode has no signups, so it skips this.
 */
async function assertSenderVerified(userId: string) {
  if (process.env.SHOGO_LOCAL_MODE === 'true') return
  const user = await db.user.findUnique({ where: { id: userId }, select: { emailVerified: true } })
  if (user?.emailVerified !== true) {
    throw new MailError(403, 'email_verification_required', 'Verify your email before sending mail. Check your inbox for the link, or resend it from Settings.')
  }
  const hold = await getSignupTrustHold(userId)
  if (hold) throw new MailError(403, hold, SIGNUP_TRUST_MESSAGES[hold])
}

