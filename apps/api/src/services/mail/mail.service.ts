export type MailView = 'inbox' | 'feed' | 'paper_trail' | 'screener' | 'done' | 'snoozed' | 'assigned' | 'spam' | 'all'

function viewWhere(view: MailView, userId: string | null, now: Date): Record<string, unknown> {
  const awake = { OR: [{ snoozedUntil: null }, { snoozedUntil: { lte: now } }] }
  switch (view) {
    case 'feed': return { category: 'feed', status: { not: 'done' }, ...awake }
    case 'paper_trail': return { category: 'paper_trail' }
    case 'screener': return { category: 'screener' }
    case 'spam': return { category: 'spam' }
    case 'done': return { status: 'done', category: { notIn: ['spam', 'screener'] } }
    case 'snoozed': return { snoozedUntil: { gt: now } }
    case 'assigned': return { assigneeUserId: userId ?? '__none__', status: { not: 'done' } }
    case 'all': return {}
    default: return { category: 'important', status: { not: 'done' }, ...awake }
  }
}

async function listThreadsFor(mailbox: any, viewer: string | null, opts: { view?: unknown; q?: unknown; limit?: unknown; before?: unknown }) {
  const now = new Date()
  const view = (typeof opts.view === 'string' ? opts.view : 'inbox') as MailView
  const limit = Math.min(Math.max(Number(opts.limit) || 50, 1), 200)
  const where: Record<string, unknown> = { mailboxId: mailbox.id, ...viewWhere(view, viewer, now) }
  const and: unknown[] = []
  if (typeof opts.before === 'string' && opts.before) and.push({ lastMessageAt: { lt: new Date(opts.before) } })
  if (typeof opts.q === 'string' && opts.q.trim()) {
    const q = opts.q.trim().toLowerCase()
    and.push({ OR: [{ normalizedSubject: { contains: q } }, { participants: { contains: q } }] })
  }
  if (and.length) where.AND = and
  const rows = await db.mailThread.findMany({ where, orderBy: { lastMessageAt: 'desc' }, take: limit })
  const latest = rows.length
    ? await db.mailMessage.findMany({
        where: { threadId: { in: rows.map((r: any) => r.id) } },
        orderBy: { createdAt: 'desc' },
        select: { threadId: true, snippet: true, fromAddress: true, fromName: true, direction: true },
      })
    : []
  const byThread = new Map<string, any>()
  for (const m of latest) if (!byThread.has(m.threadId)) byThread.set(m.threadId, m)
  return rows.map((r: any) => serializeThread(r, { latest: byThread.get(r.id), conversationId: mailbox.conversationId }))
}

