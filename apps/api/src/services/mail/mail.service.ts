/** The workspace's row for the free shared domain; created on first use. */
export async function ensureSharedDomain(workspaceId: string) {
  const domain = sharedMailDomain()
  const existing = await db.mailDomain.findUnique({ where: { workspaceId_domain: { workspaceId, domain } } })
  if (existing) return existing
  try {
    return await db.mailDomain.create({
      data: { workspaceId, domain, mode: 'shogo', status: 'active', provider: 'shogo', records: '[]', verifiedAt: new Date() },
    })
  } catch {
    return db.mailDomain.findUnique({ where: { workspaceId_domain: { workspaceId, domain } } })
  }
}

export async function getMailOverview(workspaceId: string, userId: string) {
  const role = await requireMember(workspaceId, userId)
  await ensureSharedDomain(workspaceId)
  const [limits, used, domains, mailboxes] = await Promise.all([
    limitsFor(workspaceId),
    recipientsSentSince(workspaceId, new Date(Date.now() - 24 * 60 * 60_000)),
    db.mailDomain.findMany({ where: { workspaceId }, orderBy: { createdAt: 'asc' } }),
    db.mailbox.findMany({ where: { workspaceId, archivedAt: null }, include: { accounts: true }, orderBy: { createdAt: 'asc' } }),
  ])
  const admin = role === 'owner' || role === 'admin'
  let visible = mailboxes
  if (!admin) {
    const memberships = await db.conversationMember.findMany({
      where: { userId, conversationId: { in: mailboxes.map((m: any) => m.conversationId) } },
      select: { conversationId: true },
    })
    const mine = new Set(memberships.map((m: any) => m.conversationId))
    visible = mailboxes.filter((m: any) => mine.has(m.conversationId))
  }
  const provider = getMailProvider()
  return {
    enabled: true,
    provider: provider.name,
    sharedDomain: sharedMailDomain(),
    limits,
    usage: { sent24h: used },
    domains: domains.map(serializeDomain),
    mailboxes: visible.map(serializeMailbox),
  }
}

// ─── Domains ─────────────────────────────────────────────────────────────────

export async function addDomain(workspaceId: string, userId: string, input: { domain?: unknown; mode?: unknown }) {
  await requireAdmin(workspaceId, userId)
  const domain = String(input.domain ?? '').trim().toLowerCase().replace(/^@/, '').replace(/\.$/, '')
  if (!isValidDomain(domain)) throw new MailError(400, 'invalid_domain', 'Enter a domain like acme.com or mail.acme.com')
  if (domain === sharedMailDomain() || domain.endsWith(`.${sharedMailDomain()}`)) {
    throw new MailError(400, 'invalid_domain', 'That domain belongs to Shogo')
  }
  const mode = input.mode === 'subdomain' || domain.split('.').length > 2 ? 'subdomain' : 'full'
  const limits = await limitsFor(workspaceId)
  const count = await db.mailDomain.count({ where: { workspaceId, mode: { not: 'shogo' } } })
  if (count >= limits.maxCustomDomains) {
    throw new MailError(403, 'domain_limit', `Your plan allows ${limits.maxCustomDomains} custom email domain${limits.maxCustomDomains === 1 ? '' : 's'}`)
  }
  const taken = await db.mailDomain.findFirst({ where: { domain, workspaceId: { not: workspaceId }, status: 'active' } })
  if (taken) throw new MailError(409, 'domain_taken', 'Another workspace already receives mail on that domain')
  const existing = await db.mailDomain.findUnique({ where: { workspaceId_domain: { workspaceId, domain } } })
  if (existing) return serializeDomain(existing)
  const provider = getMailProvider()
  let created
  try {
    created = await provider.createDomain(domain)
  } catch (err) {
    throw new MailError(502, 'provider_error', `Could not add the domain: ${(err as Error).message}`)
  }
  const row = await db.mailDomain.create({
    data: {
      workspaceId,
      domain,
      mode,
      status: created.status,
      provider: provider.name,
      providerDomainId: created.providerDomainId,
      records: JSON.stringify(created.records),
      ...(created.status === 'active' ? { verifiedAt: new Date() } : {}),
    },
  })
  return serializeDomain(row)
}

async function refreshDomain(row: any, opts: { verify: boolean }) {
  if (row.mode === 'shogo' || !row.providerDomainId) return row
  const provider = getMailProvider()
  try {
    const state = opts.verify ? await provider.verifyDomain(row.providerDomainId) : await provider.getDomain(row.providerDomainId)
    return await db.mailDomain.update({
      where: { id: row.id },
      data: {
        status: state.status,
        records: JSON.stringify(state.records),
        lastCheckedAt: new Date(),
        lastError: null,
        ...(state.status === 'active' && !row.verifiedAt ? { verifiedAt: new Date() } : {}),
      },
    })
  } catch (err) {
    return db.mailDomain.update({ where: { id: row.id }, data: { lastCheckedAt: new Date(), lastError: (err as Error).message.slice(0, 500) } })
  }
}

async function domainFor(workspaceId: string, domainId: string) {
  const row = await db.mailDomain.findUnique({ where: { id: domainId } })
  if (!row || row.workspaceId !== workspaceId) throw notFound('Domain')
  return row
}

export async function verifyDomain(workspaceId: string, userId: string, domainId: string) {
  await requireAdmin(workspaceId, userId)
  return serializeDomain(await refreshDomain(await domainFor(workspaceId, domainId), { verify: true }))
}

export async function resumeDomain(workspaceId: string, userId: string, domainId: string) {
  await requireAdmin(workspaceId, userId)
  await domainFor(workspaceId, domainId)
  return serializeDomain(await db.mailDomain.update({ where: { id: domainId }, data: { sendingPausedAt: null, pauseReason: null } }))
}

export async function removeDomain(workspaceId: string, userId: string, domainId: string) {
  await requireAdmin(workspaceId, userId)
  const row = await domainFor(workspaceId, domainId)
  if (row.mode === 'shogo') throw new MailError(400, 'shared_domain', 'The shared Shogo domain cannot be removed')
  const live = await db.mailbox.count({ where: { domainId, archivedAt: null } })
  if (live) throw new MailError(409, 'domain_in_use', `Archive the ${live} mailbox${live === 1 ? '' : 'es'} on ${row.domain} first`)
  if (row.providerDomainId) await getMailProvider().deleteDomain(row.providerDomainId).catch(() => {})
  await db.mailDomain.delete({ where: { id: domainId } })
  return { ok: true }
}

/** Background: re-check domains still waiting on DNS. */
export async function recheckPendingDomains(now = new Date()): Promise<number> {
  const home = homeRegionWorkspaceWhere()
  const rows = await db.mailDomain.findMany({
    where: {
      status: { in: ['pending', 'verifying'] },
      mode: { not: 'shogo' },
      OR: [{ lastCheckedAt: null }, { lastCheckedAt: { lt: new Date(now.getTime() - DOMAIN_RECHECK_MS) } }],
      ...(home ? { workspace: home } : {}),
    },
    take: 20,
  })
  for (const row of rows) await refreshDomain(row, { verify: true })
  return rows.length
}

