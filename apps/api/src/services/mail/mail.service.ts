/** Wake snoozed threads whose time came: they reopen at the top of the inbox. */
export async function wakeSnoozedThreads(now = new Date()): Promise<number> {
  const home = homeRegionWorkspaceWhere()
  const { count } = await db.mailThread.updateMany({
    where: { snoozedUntil: { lte: now }, ...(home ? { mailbox: { workspace: home } } : {}) },
    data: { snoozedUntil: null, status: 'open', lastMessageAt: now },
  })
  return count
}
