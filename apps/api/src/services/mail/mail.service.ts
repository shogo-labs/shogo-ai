/** A person approves an agent's draft, optionally editing the text first. */
export async function approveMail(mailId: string, userId: string, input: { text?: unknown } = {}) {
  const { mail } = await pendingMailFor(mailId, userId)
  if (mail.status !== 'pending_approval' && mail.status !== 'draft') {
    throw new MailError(409, 'not_pending', 'This email is not waiting for approval')
  }
  const recipientsCount = readAddressJson(mail.toList).length + readAddressJson(mail.ccList).length + readAddressJson(mail.bccList).length
  await assertSenderVerified(userId)
  await assertWithinDailyLimit(mail.workspaceId, recipientsCount)
  const data: Record<string, unknown> = {
    status: 'scheduled',
    sendAfter: new Date(Date.now() + UNDO_SEND_SECONDS * 1000),
    approvedByUserId: userId,
    error: null,
  }
  const edited = typeof input.text === 'string' && input.text.trim() && input.text.trim() !== mail.textBody ? input.text.trim() : null
  if (edited) {
    data.textBody = edited
    data.snippet = snippetOf(edited)
  }
  // Two people pressing Send at once must not send it twice.
  const { count } = await db.mailMessage.updateMany({ where: { id: mailId, status: mail.status }, data })
  if (!count) throw new MailError(409, 'not_pending', 'This email changed; reload and try again')
  if (edited && mail.conversationMessageId) {
    await updateMessageInternal(mail.conversationMessageId, { text: edited, editedAt: new Date() }).catch(() => {})
  }
  return serializeMail(await syncBlock(mailId))
}

