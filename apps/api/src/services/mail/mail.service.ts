export async function updateRule(ruleId: string, userId: string, body: Record<string, any>) {
  const rule = await ruleFor(ruleId, userId)
  const data: Record<string, unknown> = {}
  if (typeof body.name === 'string') data.name = body.name.trim().slice(0, 100) || rule.name
  if (typeof body.instruction === 'string') data.instruction = body.instruction.trim().slice(0, 1000)
  if (typeof body.enabled === 'boolean') data.enabled = body.enabled
  if (typeof body.position === 'number') data.position = Math.max(0, Math.round(body.position))
  if (body.match || body.action) {
    const parsed = ruleInput({ match: body.match ?? readJson(rule.match, {}), action: body.action ?? readJson(rule.action, {}) })
    data.match = JSON.stringify(parsed.match)
    data.action = JSON.stringify(parsed.action)
  }
  return serializeRule(await db.mailRule.update({ where: { id: ruleId }, data }))
}

export async function deleteRule(ruleId: string, userId: string) {
  await ruleFor(ruleId, userId)
  await db.mailRule.delete({ where: { id: ruleId } })
  return { ok: true }
}

