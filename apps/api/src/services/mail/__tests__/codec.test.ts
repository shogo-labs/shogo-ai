import { describe, expect, test } from 'bun:test'
import {
  categorize,
  formatAddress,
  htmlToText,
  isAutoGenerated,
  isValidDomain,
  isValidLocalPart,
  looksBulk,
  mboxEntry,
  normalizeSubject,
  parseAddress,
  parseAddressList,
  parseMessageIds,
  replyReferences,
  replySubject,
  ruleMatches,
  stripQuotedReply,
  textToHtml,
} from '../codec'
import { reputationVerdict } from '../limits'

describe('addresses', () => {
  test('reads the forms people paste', () => {
    expect(parseAddress('Jane@Acme.com')).toEqual({ address: 'jane@acme.com', name: null })
    expect(parseAddress('Jane Doe <jane@acme.com>')).toEqual({ address: 'jane@acme.com', name: 'Jane Doe' })
    expect(parseAddress('"Doe, Jane" <jane@acme.com>')).toEqual({ address: 'jane@acme.com', name: 'Doe, Jane' })
    expect(parseAddress({ email: 'a@b.io', name: 'A' })).toEqual({ address: 'a@b.io', name: 'A' })
    expect(parseAddress('not an address')).toBeNull()
    expect(parseAddress('a@localhost')).toBeNull()
  })

  test('splits lists on commas outside quotes, drops duplicates, reports what it could not read', () => {
    const { addresses, invalid } = parseAddressList('"Doe, Jane" <jane@acme.com>, bob@acme.com; JANE@acme.com, nope')
    expect(addresses.map((a) => a.address)).toEqual(['jane@acme.com', 'bob@acme.com'])
    expect(invalid).toEqual(['nope'])
  })

  test('quotes display names that need it', () => {
    expect(formatAddress({ address: 'a@b.io', name: 'Doe, Jane' })).toBe('"Doe, Jane" <a@b.io>')
    expect(formatAddress({ address: 'a@b.io', name: 'Jane' })).toBe('Jane <a@b.io>')
    expect(formatAddress({ address: 'a@b.io' })).toBe('a@b.io')
  })

  test('domains and local parts', () => {
    expect(isValidDomain('acme.com')).toBe(true)
    expect(isValidDomain('mail.acme.co.uk')).toBe(true)
    expect(isValidDomain('acme')).toBe(false)
    expect(isValidDomain('-acme.com')).toBe(false)
    expect(isValidLocalPart('support')).toBe(true)
    expect(isValidLocalPart('first.last')).toBe(true)
    expect(isValidLocalPart('a..b')).toBe(false)
    expect(isValidLocalPart('.a')).toBe(false)
    expect(isValidLocalPart('Upper')).toBe(false)
  })
})

describe('threading', () => {
  test('subjects match without Re:/Fwd: prefixes', () => {
    expect(normalizeSubject('Re: RE: Fwd:  Invoice   #42')).toBe('invoice #42')
    expect(normalizeSubject('AW: Termin')).toBe('termin')
    expect(replySubject('Invoice #42')).toBe('Re: Invoice #42')
    expect(replySubject('re: Invoice #42')).toBe('re: Invoice #42')
    expect(replySubject('')).toBe('Re: (no subject)')
  })

  test('References carry the parent and its history, capped', () => {
    expect(parseMessageIds('<a@x> <b@x>\r\n <c@x>')).toEqual(['<a@x>', '<b@x>', '<c@x>'])
    expect(replyReferences({ rfcMessageId: '<c@x>', references: '<a@x> <b@x>' })).toBe('<a@x> <b@x> <c@x>')
    const long = Array.from({ length: 30 }, (_, i) => `<m${i}@x>`).join(' ')
    const refs = parseMessageIds(replyReferences({ rfcMessageId: '<last@x>', references: long }))
    expect(refs).toHaveLength(20)
    expect(refs[0]).toBe('<m0@x>')
    expect(refs[19]).toBe('<last@x>')
  })

  test('quoted history is cut from a reply', () => {
    expect(stripQuotedReply('Sounds good!\n\nOn Tue, Nov 17, 2026 at 9:00 AM Jane <jane@acme.com> wrote:\n> earlier')).toBe('Sounds good!')
    expect(stripQuotedReply('Yes.\n\n-----Original Message-----\nFrom: x')).toBe('Yes.')
    expect(stripQuotedReply('Ok\nFrom: Jane\nSent: Monday\nSubject: x')).toBe('Ok')
    expect(stripQuotedReply('Fine\n> a\n> b\n')).toBe('Fine')
    expect(stripQuotedReply('> only a quote')).toBe('> only a quote')
  })
})

describe('content', () => {
  test('HTML to text keeps the words and the line breaks', () => {
    expect(htmlToText('<style>p{}</style><p>Hello&nbsp;<b>there</b></p><p>Line&amp;two</p><ul><li>a</li></ul>')).toBe('Hello there\nLine&two\n• a')
  })

  test('text to HTML escapes and links', () => {
    const html = textToHtml('<script>x</script> see https://shogo.ai/x?a=1')
    expect(html).not.toContain('<script>')
    expect(html).toContain('&lt;script&gt;')
    expect(html).toContain('<a href="https://shogo.ai/x?a=1">')
  })

  test('mbox escapes From lines in bodies', () => {
    const entry = mboxEntry('a@b.io', new Date('2026-11-18T00:00:00Z'), 'Subject: x\r\n\r\nFrom here on\r\n')
    expect(entry.startsWith('From a@b.io Wed, 18 Nov 2026 00:00:00 GMT\n')).toBe(true)
    expect(entry).toContain('\n>From here on\n')
  })
})

describe('sorting', () => {
  test('bulk and auto mail are recognised from headers', () => {
    expect(looksBulk({ 'list-unsubscribe': '<mailto:x>' })).toBe(true)
    expect(looksBulk({ precedence: 'bulk' })).toBe(true)
    expect(looksBulk({})).toBe(false)
    expect(isAutoGenerated({ 'auto-submitted': 'auto-replied' }, 'jane@acme.com')).toBe(true)
    expect(isAutoGenerated({}, 'MAILER-DAEMON@acme.com')).toBe(true)
    expect(isAutoGenerated({}, 'noreply@acme.com')).toBe(true)
    expect(isAutoGenerated({}, 'jane@acme.com')).toBe(false)
  })

  test('first landing place: decisions beat the screener, the screener beats bulk', () => {
    expect(categorize({ bulk: false, screened: true })).toBe('screener')
    expect(categorize({ bulk: true, screened: false })).toBe('feed')
    expect(categorize({ bulk: false, screened: false })).toBe('important')
    expect(categorize({ bulk: true, screened: true, decision: 'allow' })).toBe('important')
    expect(categorize({ bulk: false, screened: false, decision: 'block' })).toBe('spam')
    expect(categorize({ bulk: false, screened: true, decision: 'paper_trail' })).toBe('paper_trail')
  })

  test('rules need every clause to match, and at least one clause', () => {
    const mail = { from: 'billing@stripe.com', to: ['support@acme.com'], subject: 'Your invoice', body: 'Amount due', hasAttachment: true, bulk: false }
    expect(ruleMatches({ fromDomain: 'stripe.com', subject: 'invoice' }, mail)).toBe(true)
    expect(ruleMatches({ fromDomain: '@stripe.com' }, mail)).toBe(true)
    expect(ruleMatches({ from: 'billing', subject: 'refund' }, mail)).toBe(false)
    expect(ruleMatches({ hasAttachment: true }, mail)).toBe(true)
    expect(ruleMatches({}, mail)).toBe(false)
  })

  test('reputation pauses past 5% hard bounces or 0.3% complaints, once there is enough to judge', () => {
    expect(reputationVerdict({ sent: 10, bounced: 5, complained: 0 })).toBeNull()
    expect(reputationVerdict({ sent: 200, bounced: 10, complained: 0 })).toBeNull()
    expect(reputationVerdict({ sent: 200, bounced: 11, complained: 0 })).toContain('Hard bounces')
    expect(reputationVerdict({ sent: 400, bounced: 0, complained: 1 })).toBeNull()
    expect(reputationVerdict({ sent: 400, bounced: 0, complained: 2 })).toContain('Spam complaints')
  })
})
