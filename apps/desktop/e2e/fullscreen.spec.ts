/**
 * SHO-262 — a `<video>`'s native fullscreen control has to actually work on
 * desktop.
 *
 * In-app videos are plain `<video controls>` (team chat attachments, chat
 * markdown media, the side-panel `VideoPreview`), so their fullscreen button is
 * just `element.requestFullscreen()`. Electron routes that through the
 * session's permission handlers, and `setupSessionHandlers()` used to answer
 * `false` to every permission except `'media'` — including Chromium's
 * `'fullscreen'`. The promise rejected and nothing happened on screen, which is
 * exactly the report ("when I click to make it big screen then nothing
 * happens"). The huddle window (same `session.defaultSession`) and IDE zen mode
 * were broken the same way.
 *
 * The harness compiles the real `apps/desktop/src/session-permissions.ts`,
 * wires both handlers into a session exactly the way `main.ts` does, and drives
 * a real video element in a real Electron window. The second test reproduces
 * the pre-fix handlers to prove the first one has teeth.
 *
 * GUARDED: set PLAYWRIGHT_E2E=1 to run (macOS; fullscreen is a native window
 * state, so a headless Linux runner is not a meaningful place for it).
 *
 *   cd apps/desktop
 *   PLAYWRIGHT_E2E=1 npx playwright test --config e2e/playwright.config.ts e2e/fullscreen.spec.ts
 *
 * `SHOGO_E2E_ELECTRON=/path/to/Electron` overrides the binary when the npm
 * `electron` package isn't installed (e.g. a bun-only checkout).
 */
import { _electron as electron, expect, test, type ElectronApplication, type Page } from '@playwright/test'
import { spawnSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'

test.skip(process.env.PLAYWRIGHT_E2E !== '1', 'set PLAYWRIGHT_E2E to run')

const DESKTOP_DIR = path.resolve(__dirname, '..')

const HARNESS_MAIN = `// generated by e2e/fullscreen.spec.ts
const { app, BrowserWindow, protocol, session } = require('electron')
const http = require('node:http')
const { decidePermission } = require('./session-permissions.cjs')

// 'fixed' = the branch's handlers; 'pre-fix' = the old deny-everything-but-media.
const MODE = process.env.HARNESS_PERMISSION_MODE || 'fixed'
// 'http' = a 127.0.0.1 page (the localhost canvas-preview case); 'shogo' = the
// packaged renderer on shogo://app, the origin a release build actually uses.
const ORIGIN = process.env.HARNESS_ORIGIN_MODE || 'http'
// With no dev or cloud URL configured, only the shogo:// scheme and localhost
// are app origins — exactly a packaged build.
const OPTIONS = { isDev: false }

globalThis.__SHO262_LOG = []
globalThis.__SHO262_WINDOW_ID = null

const PAGE = '<!doctype html><html><head><meta charset="utf-8"><title>sho262</title>' +
  '<style>html,body{margin:0;background:#111}#v{width:320px;height:240px;background:#000}</style>' +
  '</head><body><video id="v" controls playsinline></video></body></html>'

function installHandlers(ses) {
  ses.setPermissionRequestHandler((webContents, permission, callback, details) => {
    if (MODE === 'pre-fix') {
      // Exactly what main.ts did before the fix: only 'media' was considered,
      // and this harness page never asks for it.
      callback(false)
      return
    }
    const requestingUrl = (details && details.requestingUrl) || webContents.getURL()
    const decision = decidePermission(permission, requestingUrl, OPTIONS)
    globalThis.__SHO262_LOG.push({ via: 'request', permission, requestingUrl, decision })
    if (decision === 'media') return callback(true)
    callback(decision === 'allow')
  })

  ses.setPermissionCheckHandler((webContents, permission, requestingOrigin, details) => {
    if (MODE === 'pre-fix') return false
    // main.ts falls back when requestingOrigin is empty (it can be for a
    // non-standard scheme), so the packaged path runs here as it ships.
    const url = requestingOrigin || (details && details.requestingUrl) || (webContents && webContents.getURL && webContents.getURL()) || ''
    const decision = decidePermission(permission, url, OPTIONS)
    globalThis.__SHO262_LOG.push({ via: 'check', permission, requestingOrigin, requestingUrl: url, decision })
    return decision !== 'deny'
  })
}

function openWindow() {
  const win = new BrowserWindow({
    show: true,
    width: 1000,
    height: 800,
    webPreferences: { nodeIntegration: true, contextIsolation: false, sandbox: false },
  })
  globalThis.__SHO262_WINDOW_ID = win.id
  return win
}

if (ORIGIN === 'shogo') {
  // Privileged before 'ready', exactly like the packaged app's custom scheme.
  protocol.registerSchemesAsPrivileged([
    { scheme: 'shogo', privileges: { standard: true, secure: true, supportFetchAPI: true, corsEnabled: true } },
  ])
}

app.whenReady().then(async () => {
  installHandlers(session.defaultSession)
  if (ORIGIN === 'shogo') {
    protocol.handle('shogo', () => new Response(PAGE, { headers: { 'content-type': 'text/html; charset=utf-8' } }))
    await openWindow().loadURL('shogo://app/index.html')
    return
  }
  const server = http.createServer((_req, res) => {
    res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' })
    res.end(PAGE)
  })
  server.listen(0, '127.0.0.1', async () => {
    await openWindow().loadURL('http://127.0.0.1:' + server.address().port + '/')
  })
})

app.on('window-all-closed', () => app.quit())
`

/** Runs inside the page with a user gesture; must return JSON only. */
const ENTER_FULLSCREEN_JS = `(async () => {
  // A denied request can leave the promise unsettled in some Chromium builds,
  // so settle it ourselves rather than hanging the spec.
  const withTimeout = (promise, ms) => Promise.race([
    promise.then(() => 'resolved', (err) => 'rejected:' + String((err && err.message) || err)),
    new Promise((r) => setTimeout(() => r('timeout'), ms)),
  ])
  const video = document.getElementById('v')
  const canvas = document.createElement('canvas')
  canvas.width = 160
  canvas.height = 120
  const ctx = canvas.getContext('2d')
  const rec = new MediaRecorder(canvas.captureStream(15), { mimeType: 'video/webm' })
  const chunks = []
  rec.ondataavailable = (e) => e.data.size && chunks.push(e.data)
  const stopped = new Promise((r) => (rec.onstop = r))
  rec.start()
  for (let i = 0; i < 6; i++) {
    ctx.fillStyle = i % 2 ? '#e33' : '#3e3'
    ctx.fillRect(0, 0, 160, 120)
    await new Promise((r) => setTimeout(r, 60))
  }
  rec.stop()
  await stopped
  video.src = URL.createObjectURL(new Blob(chunks, { type: 'video/webm' }))

  const out = { outcome: null, entered: false, elementIsVideo: false, fullscreenTag: null, error: null }
  try {
    out.outcome = await withTimeout(video.requestFullscreen(), 8000)
  } catch (err) {
    out.outcome = 'threw:' + String((err && err.message) || err)
  }
  out.entered = out.outcome === 'resolved'
  out.error = out.entered ? null : out.outcome
  out.elementIsVideo = document.fullscreenElement === video
  out.fullscreenTag = document.fullscreenElement ? document.fullscreenElement.tagName : null
  return out
})()`

const EXIT_FULLSCREEN_JS = `(async () => {
  const out = { exited: false, remaining: null, error: null }
  const withTimeout = (promise, ms) => Promise.race([
    promise.then(() => 'resolved', (err) => 'rejected:' + String((err && err.message) || err)),
    new Promise((r) => setTimeout(() => r('timeout'), ms)),
  ])
  try {
    if (document.fullscreenElement) out.exited = (await withTimeout(document.exitFullscreen(), 20000)) === 'resolved'
    else out.exited = true
  } catch (err) {
    out.error = String((err && err.message) || err)
  }
  out.remaining = document.fullscreenElement ? document.fullscreenElement.tagName : null
  return out
})()`

interface EnterResult {
  outcome: string | null
  entered: boolean
  elementIsVideo: boolean
  fullscreenTag: string | null
  error: string | null
}

interface ExitResult {
  exited: boolean
  remaining: string | null
  error: string | null
}

interface PermissionLogEntry {
  via: 'request' | 'check'
  permission: string
  requestingUrl?: string
  requestingOrigin?: string
  decision: string
}

function resolveElectronExecutable(): string | undefined {
  if (process.env.SHOGO_E2E_ELECTRON) return process.env.SHOGO_E2E_ELECTRON
  try {
    const resolved = require('electron') as unknown
    if (typeof resolved === 'string') return resolved
  } catch {
    /* not installed — fall through to Playwright's default */
  }
  return undefined
}

let harnessDir: string

async function launch(mode: 'fixed' | 'pre-fix', origin: 'http' | 'shogo' = 'http'): Promise<{ app: ElectronApplication; page: Page }> {
  const app = await electron.launch({
    executablePath: resolveElectronExecutable(),
    args: [harnessDir, '--no-sandbox'],
    env: { ...process.env, HARNESS_PERMISSION_MODE: mode, HARNESS_ORIGIN_MODE: origin, ELECTRON_DISABLE_SECURITY_WARNINGS: 'true' },
    timeout: 60_000,
  })
  const page = await app.firstWindow()
  await page.waitForSelector('#v')
  return { app, page }
}

/** Run `js` in the main window with Chromium's transient user activation. */
function withGesture<T>(app: ElectronApplication, js: string): Promise<T> {
  return app.evaluate(
    async ({ BrowserWindow }, code) => {
      const win = BrowserWindow.getAllWindows()[0]
      return (await win.webContents.executeJavaScript(code, true)) as never
    },
    js,
  ) as Promise<T>
}

function isWindowFullScreen(app: ElectronApplication): Promise<boolean> {
  return app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isFullScreen()) as Promise<boolean>
}

function permissionLog(app: ElectronApplication): Promise<PermissionLogEntry[]> {
  return app.evaluate(() => ((globalThis as any).__SHO262_LOG ?? []) as never[]) as Promise<PermissionLogEntry[]>
}

test.beforeAll(() => {
  harnessDir = fs.mkdtempSync(path.join(os.tmpdir(), 'shogo-fullscreen-e2e-'))
  const built = spawnSync(
    'bun',
    [
      'build',
      path.join(DESKTOP_DIR, 'src', 'session-permissions.ts'),
      '--target=node',
      '--format=cjs',
      '--outfile',
      path.join(harnessDir, 'session-permissions.cjs'),
    ],
    { encoding: 'utf8' },
  )
  if (built.status !== 0) throw new Error(`could not compile session-permissions.ts:\n${built.stderr || built.stdout}`)
  fs.writeFileSync(path.join(harnessDir, 'main.js'), HARNESS_MAIN)
  fs.writeFileSync(path.join(harnessDir, 'package.json'), JSON.stringify({ name: 'sho262-fullscreen-e2e', main: 'main.js' }))
})

test.afterAll(() => {
  if (process.env.HARNESS_KEEP) {
    console.log(`harness kept at ${harnessDir}`)
    return
  }
  if (harnessDir) fs.rmSync(harnessDir, { recursive: true, force: true })
})

test('a video enters fullscreen, the window follows, and Esc-equivalent exit restores it', async () => {
  const { app } = await launch('fixed')
  try {
    const entered = await withGesture<EnterResult>(app, ENTER_FULLSCREEN_JS)
    expect(entered.outcome).toBe('resolved')
    expect(entered.error).toBeNull()
    expect(entered.entered).toBe(true)
    expect(entered.elementIsVideo).toBe(true)
    expect(entered.fullscreenTag).toBe('VIDEO')

    // The OS window follows the element (this is what the user sees).
    await expect.poll(() => isWindowFullScreen(app), { timeout: 15_000 }).toBe(true)

    // macOS animates into native fullscreen; exiting mid-transition can stall.
    await app.evaluate(() => new Promise((r) => setTimeout(r, 1500)))
    const exited = await withGesture<ExitResult>(app, EXIT_FULLSCREEN_JS)
    expect(exited.error).toBeNull()
    expect(exited.exited).toBe(true)
    expect(exited.remaining).toBeNull()
    await expect.poll(() => isWindowFullScreen(app), { timeout: 15_000 }).toBe(false)

    // The decision really came from the permission module, not from Chromium.
    const log = await permissionLog(app)
    const fullscreen = log.filter((entry) => entry.permission === 'fullscreen')
    expect(fullscreen.length).toBeGreaterThan(0)
    expect(fullscreen.every((entry) => entry.decision === 'allow')).toBe(true)
  } finally {
    await app.close().catch(() => {})
  }
})

test('a packaged shogo://app renderer reaches fullscreen too (the release path)', async () => {
  const { app } = await launch('fixed', 'shogo')
  try {
    const entered = await withGesture<EnterResult>(app, ENTER_FULLSCREEN_JS)
    expect(entered.outcome).toBe('resolved')
    expect(entered.elementIsVideo).toBe(true)
    expect(entered.fullscreenTag).toBe('VIDEO')
    await expect.poll(() => isWindowFullScreen(app), { timeout: 15_000 }).toBe(true)

    const log = await permissionLog(app)
    // Every origin the check handler saw is the packaged scheme, and the
    // request itself was allowed — so the fallback in main.ts never has to
    // rescue an empty `requestingOrigin` on this path.
    const checks = log.filter((entry) => entry.via === 'check')
    expect(checks.length).toBeGreaterThan(0)
    expect(checks.some((entry) => (entry.requestingUrl ?? '').startsWith('shogo://app'))).toBe(true)
    const fullscreenRequests = log.filter((entry) => entry.via === 'request' && entry.permission === 'fullscreen')
    expect(fullscreenRequests.length).toBeGreaterThan(0)
    expect(fullscreenRequests.every((entry) => entry.decision === 'allow')).toBe(true)

    // Chromium's gesture-less `automatic-fullscreen` check stays denied: a
    // script may not take the window over, only a real user gesture may.
    const automatic = log.filter((entry) => entry.permission === 'automatic-fullscreen')
    expect(automatic.every((entry) => entry.decision === 'deny')).toBe(true)

    await app.evaluate(() => new Promise((r) => setTimeout(r, 1500)))
    const exited = await withGesture<ExitResult>(app, EXIT_FULLSCREEN_JS)
    expect(exited.error).toBeNull()
    expect(exited.remaining).toBeNull()
  } finally {
    await app.close().catch(() => {})
  }
})

test('with the pre-fix deny-everything handlers the request rejects (negative control)', async () => {
  const { app } = await launch('pre-fix')
  try {
    const entered = await withGesture<EnterResult>(app, ENTER_FULLSCREEN_JS)
    expect(entered.entered).toBe(false)
    expect(entered.outcome === 'rejected' || entered.outcome === 'timeout' || (entered.outcome || '').startsWith('threw:')).toBe(true)
    expect(entered.elementIsVideo).toBe(false)
    expect(entered.fullscreenTag).toBeNull()
    expect(await isWindowFullScreen(app)).toBe(false)
  } finally {
    await app.close().catch(() => {})
  }
})
