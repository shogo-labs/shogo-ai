/**
 * SHO-229 / SHO-224 — the local-mode CSP has to let the chat file viewer play
 * `blob:` media and render a `blob:` PDF on desktop.
 *
 * `ShareFileViewer` fetches a shared file with the app's own `fetch` and hands
 * `MediaPreview` a `blob:` URL. Desktop stamps `buildLocalCsp()` on every
 * local-mode response (`main.ts`, `onHeadersReceived`), so those elements live
 * or die by that policy:
 *
 *   - no `media-src` → `<video>`/`<audio>` fall back to `default-src`, which
 *     has no `blob:`, and the element sits at 0:00 forever;
 *   - no `blob:` in `frame-src` → the PDF frame is refused outright;
 *   - no `chrome:` in `script-src` → the frame loads but paints blank: a
 *     `blob:` document inherits this policy, and Chromium's PDF viewer builds
 *     its own UI from `chrome://resources`.
 *
 * The last one is invisible to the page — the violations fire inside the
 * viewer's document, so there is no `securitypolicyviolation` to catch. The
 * assertions below therefore read the viewer's frame directly (its custom
 * element never upgrades and no `embed` appears when its scripts are blocked),
 * which is also why the second test exists: it proves the first one has teeth.
 *
 * The harness is hermetic on purpose — it compiles the real
 * `apps/desktop/src/local-csp.ts`, stamps the header on every response the way
 * `main.ts` does, and drives blob URLs in a real Electron window. It needs no
 * packaged desktop build and no media fixtures: the webm comes from
 * MediaRecorder, and the wav and PDF are built in-page.
 *
 * GUARDED: set PLAYWRIGHT_E2E=1 to run.
 *
 *   cd apps/desktop
 *   PLAYWRIGHT_E2E=1 npx playwright test --config e2e/playwright.config.ts e2e/csp-blob-media.spec.ts
 *
 * `SHOGO_E2E_ELECTRON=/path/to/Electron` overrides the binary when the npm
 * `electron` package isn't installed (e.g. a bun-only checkout).
 */
