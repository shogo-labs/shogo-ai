function resolveElectronExecutable(): string | undefined {
  if (process.env.SHOGO_E2E_ELECTRON) return process.env.SHOGO_E2E_ELECTRON
  try {
    const resolved = require('electron') as unknown
    if (typeof resolved === 'string') return resolved
  } catch {
    /* not installed — fall through to Playwright's default */
  }
  return undefined
}

interface MediaOutcome {
  name: string
  via: string
  readyState: number
  duration: number | null
  errorCode: number | null
}

interface HarnessResults {
  media: MediaOutcome[]
  pdf: { via: string }
  violations: { directive: string; blockedURI: string }[]
  fatal?: string
}

interface Harness {
  app: ElectronApplication
  page: Page
  results: () => Promise<HarnessResults | null>
  consoleLines: () => Promise<string[]>
}

/** What the PDF viewer frame looks like from the outside. */
interface ViewerProbe {
  viewerFrameLoaded: boolean
  /** The viewer's own `pdf-viewer` custom element upgraded — i.e. its scripts ran. */
  viewerScriptRan: boolean
  /** PDFium embedded the document, so something was actually painted. */
  documentEmbedded: boolean
}

let harnessDir: string

async function launch(mode: 'local' | 'no-chrome'): Promise<Harness> {
  const app = await electron.launch({
    executablePath: resolveElectronExecutable(),
    args: [harnessDir, '--no-sandbox'],
    env: { ...process.env, HARNESS_CSP_MODE: mode, ELECTRON_DISABLE_SECURITY_WARNINGS: 'true' },
    timeout: 60_000,
  })
  const page = await app.firstWindow()
  return {
    app,
    page,
    results: () => app.evaluate(() => (globalThis as any).__SHO229_RESULTS ?? null),
    consoleLines: () => app.evaluate(() => ((globalThis as any).__SHO229_CONSOLE ?? []) as string[]),
  }
}

async function probeViewer(page: Page): Promise<ViewerProbe> {
  const viewer = page.frames().find((f) => f.url().startsWith(PDF_VIEWER_ORIGIN))
  if (!viewer) return { viewerFrameLoaded: false, viewerScriptRan: false, documentEmbedded: false }
  const viewerScriptRan = await viewer
    .evaluate(() => typeof customElements !== 'undefined' && !!customElements.get('pdf-viewer'))
    .catch(() => false)
  const embedded = await Promise.all(
    page
      .frames()
      .filter((f) => f.url().startsWith('blob:'))
      .map((f) => f.evaluate(() => !!document.querySelector('embed')).catch(() => false)),
  )
  return { viewerFrameLoaded: true, viewerScriptRan, documentEmbedded: embedded.some(Boolean) }
}

async function waitForResults(h: Harness): Promise<HarnessResults> {
  await expect
    .poll(() => h.results(), { timeout: 40_000, message: 'harness never reported results' })
    .not.toBeNull()
  const results = (await h.results()) as HarnessResults
  expect(results.fatal).toBeUndefined()
  return results
}

test.beforeAll(() => {
  harnessDir = fs.mkdtempSync(path.join(os.tmpdir(), 'shogo-csp-e2e-'))
  const built = spawnSync(
    'bun',
    [
      'build',
      path.join(DESKTOP_DIR, 'src', 'local-csp.ts'),
      '--target=node',
      '--format=cjs',
      '--outfile',
      path.join(harnessDir, 'local-csp.cjs'),
    ],
    { encoding: 'utf8' },
  )
  if (built.status !== 0) throw new Error(`could not compile local-csp.ts:\n${built.stderr || built.stdout}`)
  fs.writeFileSync(path.join(harnessDir, 'main.js'), HARNESS_MAIN)
  fs.writeFileSync(path.join(harnessDir, 'package.json'), JSON.stringify({ name: 'sho229-csp-e2e', main: 'main.js' }))
})

test.afterAll(() => {
  if (process.env.HARNESS_KEEP) {
    console.log(`harness kept at ${harnessDir}`)
    return
  }
  if (harnessDir) fs.rmSync(harnessDir, { recursive: true, force: true })
})

test('blob: media plays and the blob: PDF paints under the local-mode CSP', async () => {
  const h = await launch('local')
  try {
    const results = await waitForResults(h)

    // AC: a shared .webm plays in the panel — a blocked source leaves
    // readyState 0 and MEDIA_ERR_SRC_NOT_SUPPORTED (code 4) at 0:00.
    const video = results.media.find((m) => m.name === 'webm')!
    expect(video.via).toBe('loadedmetadata')
    expect(video.readyState).toBeGreaterThanOrEqual(1)
    expect(video.duration).toBeGreaterThan(0)
    expect(video.errorCode).toBeNull()

    // AC: a shared .wav/.mp3 plays in the same panel.
    const audio = results.media.find((m) => m.name === 'wav')!
    expect(audio.via).toBe('loadedmetadata')
    expect(audio.readyState).toBeGreaterThanOrEqual(1)
    expect(audio.duration).toBeGreaterThan(0)

    // AC: no `Refused to load media` / `Refused to frame` for blob:.
    expect(results.violations.filter((v) => v.blockedURI === 'blob')).toEqual([])
    expect(results.pdf.via).toBe('load')

    // AC: the PDF renders — the viewer's own UI ran and PDFium embedded the
    // document. Neither is visible as a page violation (they happen inside the
    // viewer's frame), so the frame is inspected directly.
    const probe = await probeViewer(h.page)
    expect(probe.viewerFrameLoaded).toBe(true)
    expect(probe.viewerScriptRan).toBe(true)
    expect(probe.documentEmbedded).toBe(true)

    // The viewer's chrome://resources script must not be refused by script-src.
    // Its default stylesheet is not asserted: a missing chrome:// stylesheet is
    // cosmetic console noise and the document renders either way.
    const refusedViewerScript = (await h.consoleLines()).filter(
      (line) => line.includes('chrome://resources') && line.includes('script-src'),
    )
    expect(refusedViewerScript).toEqual([])

    // Full-page capture, not `locator('#pdf').screenshot()`: the viewer is an
    // out-of-process frame and an element screenshot of it comes back blank.
    await h.page.screenshot({ path: test.info().outputPath('blob-pdf-window.png') })
  } finally {
    await h.app.close().catch(() => {})
  }
})

test('without chrome: in script-src the PDF frame loads but paints nothing', async () => {
  // Negative control: proves the assertions above have teeth, and that `chrome:`
  // is what makes the frame render rather than merely load.
  const h = await launch('no-chrome')
  try {
    const results = await waitForResults(h)

    // frame-src still allows the blob, so the page sees no violation at all —
    // this is exactly the silent failure the fix removes.
    expect(results.pdf.via).toBe('load')
    expect(results.violations.filter((v) => v.blockedURI === 'blob')).toEqual([])

    const probe = await probeViewer(h.page)
    expect(probe.viewerFrameLoaded).toBe(true)
    expect(probe.viewerScriptRan).toBe(false)
    expect(probe.documentEmbedded).toBe(false)

    const refusedViewerScript = (await h.consoleLines()).filter(
      (line) => line.includes('chrome://resources') && line.includes('script-src'),
    )
    expect(refusedViewerScript.length).toBeGreaterThan(0)
  } finally {
    await h.app.close().catch(() => {})
  }
})
