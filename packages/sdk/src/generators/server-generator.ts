/**
 * Hono Server Generator
 *
 * Generates a complete Hono server entry point that:
 * - Sets up CORS middleware
 * - Adds health endpoint
 * - Mounts SDK-generated routes at /api
 * - Serves static files for production
 * - Exports Bun-compatible server
 */

import { GENERATED_FILE_LICENSE_HEADER } from './generated-file-license-header'

export interface ServerGeneratorConfig {
  /** Port to run server on (default: 3000) */
  port?: number
  /** Enable CORS (default: true) */
  cors?: boolean
  /** CORS origins (default: localhost:5173, localhost:3000) */
  corsOrigins?: string[]
  /** Path to generated routes (default: './src/generated') */
  routesPath?: string
  /** Path to Prisma db module (default: './src/lib/db') */
  dbPath?: string
  /** API base path (default: '/api') */
  apiBasePath?: string
  /** Static files directory (default: './dist') */
  staticDir?: string
  /** Skip static file serving (useful for API-only servers) */
  skipStatic?: boolean
  /** Path to custom routes file (e.g. './custom-routes'). When set, the
   *  server statically imports and mounts the file at the API base path. */
  customRoutesPath?: string
  /** Use dynamic import() for CRUD routes + Prisma so the server starts
   *  even before any schema models are generated. */
  dynamicCrudImport?: boolean
  /** Emit Bun.serve() instead of export default { port, fetch } to avoid
   *  the Bun 1.3 double-bind issue. */
  bunServe?: boolean
  /** Mount the installed-integration tools proxy at `<apiBasePath>/tools/*`.
   *  When true (default), emits `createToolsHandlers()` from
   *  `@shogo-ai/sdk/tools/server` before the static catch-all so
   *  `fetch('/api/tools/*')` from the SPA reaches the runtime instead
   *  of falling through to `index.html`. Disable only when the pod
   *  shouldn't expose installed integrations to its own origin. */
  tools?: boolean
}

/**
 * Generate Hono server entry point
 */
export function generateServer(config: ServerGeneratorConfig = {}): string {
  const {
    port = 3000,
    cors = true,
    corsOrigins = ['http://localhost:5173', 'http://localhost:3000'],
    routesPath = './src/generated',
    dbPath = './src/lib/db',
    apiBasePath = '/api',
    staticDir = './dist',
    skipStatic = false,
    customRoutesPath,
    dynamicCrudImport = false,
    bunServe = false,
    tools = true,
  } = config

  const lines: string[] = [
    GENERATED_FILE_LICENSE_HEADER,
    '/**',
    ' * Hono Server',
    ' *',
    ' * Auto-generated by @shogo-ai/sdk',
    ' * This file can be customized - it will not be overwritten if it exists.',
    ' */',
    '',
    "import { Hono } from 'hono'",
  ]

  // cors import intentionally omitted — using manual middleware for reliable wildcard support

  if (!skipStatic) {
    lines.push("import { serveStatic } from 'hono/bun'")
  }

  if (!dynamicCrudImport) {
    lines.push(`import { createAllRoutes } from '${routesPath}'`)
    lines.push(`import { prisma } from '${dbPath}'`)
  }

  if (customRoutesPath) {
    lines.push(`import customRoutes from '${customRoutesPath}'`)
  }

  if (tools) {
    lines.push("import { createToolsHandlers } from '@shogo-ai/sdk/tools/server'")
  }

  lines.push('')
  lines.push('const app = new Hono()')
  lines.push('')

  if (cors) {
    lines.push('// CORS — manual middleware so the wildcard always propagates')
    lines.push("app.use('*', async (c, next) => {")
    lines.push("  c.res.headers.set('Access-Control-Allow-Origin', '*')")
    lines.push("  c.res.headers.set('Access-Control-Allow-Methods', 'GET,POST,PUT,PATCH,DELETE,OPTIONS')")
    lines.push("  c.res.headers.set('Access-Control-Allow-Headers', 'Content-Type,Authorization')")
    lines.push("  if (c.req.method === 'OPTIONS') return new Response(null, { status: 204 })")
    lines.push('  await next()')
    lines.push('})')
    lines.push('')
  }

  lines.push('// Health check endpoint')
  lines.push("app.get('/health', (c) => c.json({ ok: true, timestamp: new Date().toISOString() }))")
  lines.push('')

  if (dynamicCrudImport) {
    lines.push('// CRUD routes (available after schema.prisma has models)')
    lines.push('try {')
    lines.push(`  const { createAllRoutes } = await import('${routesPath}')`)
    lines.push(`  const { prisma } = await import('${dbPath}')`)
    lines.push(`  app.route('${apiBasePath}', createAllRoutes(prisma))`)
    lines.push('} catch {')
    lines.push('  // No generated routes yet — CRUD routes will appear after schema.prisma is written')
    lines.push('}')
  } else {
    lines.push('// Mount SDK-generated API routes')
    lines.push(`app.route('${apiBasePath}', createAllRoutes(prisma))`)
  }
  lines.push('')

  if (customRoutesPath) {
    lines.push('// Custom API routes (always mounted)')
    lines.push(`app.route('${apiBasePath}', customRoutes)`)
    lines.push('')
  }

  if (tools) {
    // Mounted BEFORE the static catch-all so `fetch('/api/tools/*')` from
    // the SPA reaches the proxy instead of falling through to index.html.
    lines.push('// Installed-integration tools proxy → forwards to the agent runtime')
    lines.push('// using RUNTIME_AUTH_SECRET + RUNTIME_PORT (auto-detected from env).')
    lines.push('const tools = createToolsHandlers({})')
    lines.push(`app.post('${apiBasePath}/tools/execute', (c) => tools.execute(c.req.raw))`)
    lines.push(`app.get('${apiBasePath}/tools/schemas', (c) => tools.list(c.req.raw))`)
    lines.push('')
  }

  // Runtime introspection. The agent runtime's API proxy uses these to know
  // whether this server is really up and which routes it really registered
  // (custom routes included) instead of guessing from generated files.
  // `/__shogo/*` sits outside the API base path so app routes cannot collide.
  // Registered BEFORE the static catch-all so it can't swallow them; each
  // handler reads `app.routes` at request time, so anything mounted later is
  // still listed.
  lines.push('// Runtime introspection (the agent runtime proxies these; never public)')
  lines.push('const startedAt = new Date().toISOString()')
  lines.push("app.get('/__shogo/health', (c) => c.json({ ok: true, startedAt, pid: process.pid }))")
  lines.push("app.get('/__shogo/routes', (c) => {")
  lines.push('  const seen = new Set<string>()')
  lines.push('  const routes: { method: string; path: string }[] = []')
  lines.push('  for (const route of app.routes) {')
  lines.push('    const method = String(route.method).toUpperCase()')
  lines.push("    if (method === 'ALL' || method === 'USE') continue")
  lines.push("    if (route.path.startsWith('/__shogo')) continue")
  // Only the API surface: `/health` and the SPA catch-all are real routes but
  // not API routes, and the runtime reports this list as `/api/<path>`.
  lines.push(`    if (!route.path.startsWith('${apiBasePath}'.replace(/\\/$/, '') + '/')) continue`)
  lines.push('    const key = `${method} ${route.path}`')
  lines.push('    if (seen.has(key)) continue')
  lines.push('    seen.add(key)')
  lines.push('    routes.push({ method, path: route.path })')
  lines.push('  }')
  lines.push('  return c.json({ routes })')
  lines.push('})')
  lines.push('')

  if (!skipStatic) {
    lines.push('// Serve static files in production')
    lines.push(`app.use('/*', serveStatic({ root: '${staticDir}' }))`)
    lines.push(`app.get('*', serveStatic({ path: '${staticDir}/index.html' }))`)
    lines.push('')
  }

  lines.push(`const port = Number(process.env.PORT) || ${port}`)
  lines.push('console.log(`🚀 Server running on http://localhost:${port}`)')
  lines.push('')

  if (bunServe) {
    lines.push('Bun.serve({ port, fetch: app.fetch })')
  } else {
    lines.push('export default {')
    lines.push('  port,')
    lines.push('  fetch: app.fetch,')
    lines.push('}')
  }
  lines.push('')

  return lines.join('\n')
}

/**
 * The Postgres URL test, in one place: `databaseUrlGuard` compiles it, and the
 * generated client modules embed it as a literal so an image that boots with a
 * mismatched client and URL stops before serving a single request.
 */
const POSTGRES_URL_SOURCE = '^postgres(ql)?:\\/\\/'
const POSTGRES_URL_RE = new RegExp(POSTGRES_URL_SOURCE, 'i')

/**
 * Lines every generated client module carries: refuse to start when
 * `DATABASE_URL` and the driver disagree (SHO-551 AC 3).
 *
 * A published Postgres pod that boots with the SQLite client (or the reverse)
 * otherwise answers 500 on every query, and the revision still reports ready.
 * Exiting with one named line makes it a failed revision instead. An unset
 * `DATABASE_URL` is left alone — local dev and CI boot without one.
 */
function databaseBootGuardLines(kind: 'postgres' | 'sqlite'): string[] {
  const urlCheck = kind === 'postgres' ? `!POSTGRES_URL.test(databaseUrl)` : `POSTGRES_URL.test(databaseUrl)`
  const expected = kind === 'postgres' ? 'a Postgres URL (PrismaPg client)' : 'the SQLite client'
  return [
    `// Database URL / driver boot guard: a mismatch is a failed revision, not a 500 on every query.`,
    `const POSTGRES_URL = /${POSTGRES_URL_SOURCE}/i`,
    `const databaseUrl = (process.env.DATABASE_URL ?? '').trim()`,
    `if (databaseUrl && ${urlCheck}) {`,
    `  console.error(`,
    `    '[db] Refusing to start: DATABASE_URL is "' +`,
    `      databaseUrl.replace(/:[^:@/]*@/, ':***@') +`,
    `      '" but this client expects ${expected}. ' +`,
    `      (${kind === 'postgres' ? `'Point DATABASE_URL at Postgres, or publish with the SQLite client.'` : `'Re-publish so the Postgres db client is generated for this environment.'`}),`,
    `  )`,
    `  process.exit(1)`,
    `}`,
    '',
  ]
}

/**
 * Generate Prisma database module (PostgreSQL with adapter)
 */
export function generateDbModule(): string {
  const lines = [
    GENERATED_FILE_LICENSE_HEADER,
    '/**',
    ' * Prisma Database Client',
    ' *',
    ' * Auto-generated by @shogo-ai/sdk',
    ' * This file can be customized - it will not be overwritten if it exists.',
    ' */',
    '',
    "import { PrismaPg } from '@prisma/adapter-pg'",
    "import { PrismaClient } from '../generated/prisma/client'",
    '',
    ...databaseBootGuardLines('postgres'),
    'const globalForPrisma = globalThis as unknown as {',
    '  prisma: PrismaClient | undefined',
    '}',
    '',
    'const adapter = new PrismaPg({',
    '  connectionString: process.env.DATABASE_URL,',
    '})',
    '',
    'export const prisma =',
    '  globalForPrisma.prisma ??',
    '  new PrismaClient({',
    '    adapter,',
    "    log: process.env.NODE_ENV === 'development' ? ['error', 'warn'] : ['error'],",
    '  })',
    '',
    "if (process.env.NODE_ENV !== 'production') globalForPrisma.prisma = prisma",
    '',
  ]
  return lines.join('\n')
}

/**
 * Guard that refuses to generate a SQLite db module when the app's DATABASE_URL
 * is already a Postgres connection string (SHO-551 B).
 *
 * A published Postgres pod boots with `DATABASE_URL=postgres://...`. Silently
 * replacing its db.tsx with a libsql adapter would make every query fail on a
 * driver mismatch. The guard is called before any rewrite that would down-convert
 * a Postgres app to SQLite; if the URL is Postgres the caller skips the rewrite.
 *
 * The same test is embedded in the generated client modules by
 * {@link databaseBootGuardLines}, so a mismatch already in the image fails the
 * boot rather than every request.
 */
export function databaseUrlGuard(databaseUrl: string | null | undefined): {
  isPostgres: boolean
  isSqlite: boolean
} {
  const url = (databaseUrl ?? '').trim()
  return {
    isPostgres: POSTGRES_URL_RE.test(url),
    isSqlite: !url || /^file:|\.db($|\?)|^sqlite/i.test(url),
  }
}

/**
 * Generate Prisma database module for SQLite using prisma-adapter-bun-sqlite (Prisma 7)
 */
export function generateSqliteDbModule(): string {
  const lines = [
    GENERATED_FILE_LICENSE_HEADER,
    '/**',
    ' * Prisma Database Client (SQLite via Bun adapter)',
    ' *',
    ' * Auto-generated by @shogo-ai/sdk',
    ' * This file can be customized - it will not be overwritten if it exists.',
    ' */',
    '',
    "import { PrismaBunSqlite } from 'prisma-adapter-bun-sqlite'",
    "import { PrismaClient } from './generated/prisma/client'",
    '',
    ...databaseBootGuardLines('sqlite'),
    'const globalForPrisma = globalThis as unknown as {',
    '  prisma: PrismaClient | undefined',
    '}',
    '',
    'const adapter = new PrismaBunSqlite({',
    "  url: process.env.DATABASE_URL ?? 'file:./skill.db',",
    '})',
    '',
    'export const prisma =',
    '  globalForPrisma.prisma ??',
    '  new PrismaClient({',
    '    adapter,',
    "    log: process.env.NODE_ENV === 'development' ? ['error', 'warn'] : ['error'],",
    '  })',
    '',
    "if (process.env.NODE_ENV !== 'production') globalForPrisma.prisma = prisma",
    '',
  ]
  return lines.join('\n')
}
