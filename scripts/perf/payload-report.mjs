// Report
// ---------------------------------------------------------------------------

export function sumEager(webDir, files) {
  const dir = path.join(webDir, '_expo', 'static', 'js', 'web')
  const chunks = files
    .map((file) => path.join(dir, file))
    .filter((file) => {
      try {
        return statSync(file).isFile()
      } catch {
        return false
      }
    })
    .map(attributeChunk)
  const totals = new Map()
  for (const chunk of chunks) {
    for (const module of chunk.modules) {
      const current = totals.get(module.source) ?? 0
      totals.set(module.source, current + module.bytes)
    }
  }
  return {
    chunks,
    bytes: chunks.reduce((sum, chunk) => sum + chunk.bytes, 0),
    modules: [...totals.entries()]
      .map(([source, bytes]) => ({ source, bytes }))
      .sort((a, b) => b.bytes - a.bytes),
  }
}

export function sumNative(exportDir) {
  const dir = path.join(exportDir, '_expo', 'static', 'js', 'ios')
  const files = readdirSync(dir)
    .filter((name) => name.endsWith('.js'))
    .map((name) => path.join(dir, name))
  const chunks = files.map(attributeChunk)
  const totals = new Map()
  for (const chunk of chunks) {
    for (const module of chunk.modules) {
      totals.set(module.source, (totals.get(module.source) ?? 0) + module.bytes)
    }
  }
  return {
    chunks,
    bytes: chunks.reduce((sum, chunk) => sum + chunk.bytes, 0),
    modules: [...totals.entries()]
      .map(([source, bytes]) => ({ source, bytes }))
      .sort((a, b) => b.bytes - a.bytes),
  }
}

function fmt(bytes) {
  if (bytes >= 1024 * 1024) return `${(bytes / 1024 / 1024).toFixed(2)} MB`
  return `${(bytes / 1024).toFixed(1)} KB`
}

function printTable(title, report, eagerFiles, top) {
  console.log(`\n## ${title}`)
  console.log(
    `${eagerFiles.length} files, ${report.bytes} bytes (${fmt(report.bytes)}) — ${report.modules.length} mapped modules`,
  )
  console.log('')
  console.log('| # | module | bytes | share |')
  console.log('|---|---|---:|---:|')
  report.modules.slice(0, top).forEach((module, index) => {
    const share = ((module.bytes / report.bytes) * 100).toFixed(1)
    console.log(`| ${index + 1} | \`${moduleKey(module.source)}\` | ${fmt(module.bytes)} | ${share}% |`)
  })
  const groups = new Map()
  for (const module of report.modules) {
    const key = packageOf(module.source)
    groups.set(key, (groups.get(key) ?? 0) + module.bytes)
  }
  console.log('')
  console.log('| package | bytes | share |')
  console.log('|---|---:|---:|')
  ;[...groups.entries()]
    .sort((a, b) => b[1] - a[1])
    .slice(0, top)
    .forEach(([key, bytes]) => {
      console.log(`| \`${key}\` | ${fmt(bytes)} | ${((bytes / report.bytes) * 100).toFixed(1)}% |`)
    })
}

function argValue(name) {
  const index = process.argv.indexOf(name)
  return index >= 0 ? process.argv[index + 1] : undefined
}

async function main() {
  const webDir = path.resolve(argValue('--web') ?? DEFAULT_WEB_DIR)
  const nativeDir = argValue('--native')
  const top = Number(argValue('--top') ?? 40)
  const explicit = argValue('--eager-chunks')

  const eager = explicit
    ? { files: explicit.split(',').map((file) => file.trim()).filter(Boolean), source: '--eager-chunks' }
    : await measureEagerChunks(webDir)
  const web = sumEager(webDir, eager.files)
  console.log(`Web eager set (${eager.source}): ${eager.files.length} files`)
  printTable('Web eager payload', web, eager.files, top)

  if (nativeDir) {
    const native = sumNative(path.resolve(nativeDir))
    printTable('Native (iOS) bundle payload', native, native.chunks.map((chunk) => path.basename(chunk.path)), top)
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main()
}
