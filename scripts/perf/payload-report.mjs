/**
 * Cold-start payload attribution (SHO-601).
 *
 * Answers one question: which modules are in the JavaScript the app parses
 * before its first paint, and how many bytes does each one account for?
 *
 *   node scripts/perf/payload-report.mjs                 # web, from apps/mobile/dist
 *   node scripts/perf/payload-report.mjs --native <dir>  # also a native export
 *   node scripts/perf/payload-report.mjs --markdown      # the docs/perf table
 *
 * Web: the eager set is measured, not guessed. The script serves the export
 * from a throwaway http server, opens it in Chromium and records every JS
 * response that lands before First Contentful Paint — the same definition of
 * "eager" the cold-start probe uses. Pass `--eager-chunks a.js,b.js` to skip
 * the browser and attribute an explicit list instead.
 *
 * Native: `expo export --platform ios --no-bytecode --source-maps external`
 * produces one JS file for the whole bundle; every module in it is eager, so
 * the export's own source map is the attribution.
 *
 * Sizes are *generated* bytes: each source map segment owns the minified span
 * up to the next segment on its line, so the numbers add up to the chunk size
 * instead of counting unminified source.
 */
import { createReadStream, readFileSync, readdirSync, statSync } from 'node:fs'
import { createServer } from 'node:http'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = path.resolve(__dirname, '..', '..')
const DEFAULT_WEB_DIR = path.join(REPO_ROOT, 'apps', 'mobile', 'dist')

const MIME = {
  '.js': 'text/javascript',
  '.mjs': 'text/javascript',
  '.css': 'text/css',
  '.html': 'text/html',
  '.json': 'application/json',
  '.map': 'application/json',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
  '.svg': 'image/svg+xml',
  '.woff': 'font/woff',
  '.woff2': 'font/woff2',
  '.ttf': 'font/ttf',
  '.wasm': 'application/wasm',
  '.vs': 'text/plain',
}

// ---------------------------------------------------------------------------
// Source map → generated bytes per module
// ---------------------------------------------------------------------------

const BASE64 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'
const BASE64_VALUES = new Map([...BASE64].map((char, index) => [char, index]))

function decodeVlq(segment) {
  const values = []
  let value = 0
  let shift = 0
  for (const char of segment) {
    const digit = BASE64_VALUES.get(char)
    if (digit === undefined) return null
    value += (digit & 31) << shift
    if (digit & 32) {
      shift += 5
    } else {
      const negative = value & 1
      value >>>= 1
      values.push(negative ? -value : value)
      value = 0
      shift = 0
    }
  }
  return values
}

/**
 * Sum the generated span each mapping segment covers, per source file.
 * A segment owns the bytes from its column to the next segment's column on
 * the same line (or the end of the line for the last one), which is exactly
 * the minified text that source produced.
 */
export function generatedBytesBySource(map, lineLengths) {
  const totals = new Array((map.sources || []).length).fill(0)
  if (!map.mappings) return totals
  let sourceIndex = 0
  const lines = map.mappings.split(';')
  let generatedLine = 0
  for (const line of lines) {
    if (line) {
      let generatedColumn = 0
      const segments = []
      for (const raw of line.split(',')) {
        if (!raw) continue
        const values = decodeVlq(raw)
        if (!values) break
        generatedColumn += values[0] || 0
        if (values.length > 1) sourceIndex += values[1]
        segments.push({ column: generatedColumn, source: sourceIndex })
      }
      const lineEnd = lineLengths?.[generatedLine] ?? Number.POSITIVE_INFINITY
      for (let i = 0; i < segments.length; i += 1) {
        const end = i + 1 < segments.length ? segments[i + 1].column : lineEnd
        const span = Math.max(0, end - segments[i].column)
        const source = segments[i].source
        if (source >= 0 && source < totals.length) totals[source] += span
      }
    }
    generatedLine += 1
  }
  return totals
}

function lineLengthsOf(code) {
  return code.split('\n').map((line) => line.length)
}

/** `node_modules/@scope/pkg/dist/x.js` → `@scope/pkg/dist/x.js`; app files keep their path. */
export function moduleKey(source) {
  const bunStore = source.match(/node_modules\/\.bun\/[^/]+\/node_modules\/(.+)$/)
  if (bunStore) return bunStore[1]
  const marker = 'node_modules/'
  const at = source.lastIndexOf(marker)
  if (at >= 0) return source.slice(at + marker.length)
  const mobile = source.split('apps/mobile/')[1]
  if (mobile) return mobile
  const pkg = source.split('/packages/')[1]
  if (pkg) return `packages/${pkg}`
  return source
}

export function packageOf(modulePath) {
  const marker = 'node_modules/'
  const at = modulePath.lastIndexOf(marker)
  if (at >= 0) {
    const rest = modulePath.slice(at + marker.length).split('/')
    return rest[0].startsWith('@') ? `${rest[0]}/${rest[1]}` : rest[0]
  }
  return modulePath.split('/').slice(0, 2).join('/')
}

function loadChunk(jsPath) {
  const code = readFileSync(jsPath, 'utf8')
  const mapPath = `${jsPath}.map`
  try {
    const map = JSON.parse(readFileSync(mapPath, 'utf8'))
    return { code, map, bytes: statSync(jsPath).size }
  } catch {
    return { code, map: null, bytes: statSync(jsPath).size }
  }
}

/** One chunk → per-module generated bytes, sorted descending. */
export function attributeChunk(jsPath) {
  const { code, map, bytes } = loadChunk(jsPath)
  if (!map) return { path: jsPath, bytes, modules: [], mapped: false }
  const totals = generatedBytesBySource(map, lineLengthsOf(code))
  const modules = map.sources
    .map((source, index) => ({ source, bytes: totals[index] }))
    .filter((entry) => entry.bytes > 0)
    .sort((a, b) => b.bytes - a.bytes)
  return { path: jsPath, bytes, modules, mapped: true, mappedBytes: modules.reduce((sum, m) => sum + m.bytes, 0) }
}

// ---------------------------------------------------------------------------
// Eager set: measure the real thing in a browser
// ---------------------------------------------------------------------------

function serveStatic(root) {
  const server = createServer((req, res) => {
    const url = new URL(req.url ?? '/', 'http://localhost')
    let file = path.join(root, decodeURIComponent(url.pathname))
    try {
      if (statSync(file).isDirectory()) file = path.join(file, 'index.html')
    } catch {
      res.writeHead(404).end('not found')
      return
    }
    if (!file.startsWith(root)) {
      res.writeHead(403).end('forbidden')
      return
    }
    res.writeHead(200, { 'content-type': MIME[path.extname(file)] ?? 'application/octet-stream' })
    createReadStream(file).pipe(res)
  })
  return new Promise((resolve) => {
    server.listen(0, '127.0.0.1', () => resolve({ server, port: server.address().port }))
  })
}

/**
 * Every JS file the page finished fetching before First Contentful Paint.
 * Falls back to the HTML's own `<script src>` list when no browser is present.
 */
export async function measureEagerChunks(webDir) {
  const html = readFileSync(path.join(webDir, 'index.html'), 'utf8')
  const htmlScripts = [...html.matchAll(/<script[^>]+src="([^"]+\.js)"/g)].map((m) => path.basename(m[1]))
  let chromium
  // The repo pins @playwright/test; prefer it over any global playwright so the
  // browser binary matches the version the e2e suites already downloaded.
  for (const specifier of ['@playwright/test', 'playwright']) {
    try {
      ;({ chromium } = await import(specifier))
      break
    } catch {
      // try the next one
    }
  }
  if (!chromium) return { files: htmlScripts, source: 'index.html' }
  const { server, port } = await serveStatic(webDir)
  const browser = await chromium.launch()
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
    const eager = new Set(htmlScripts)
    let firstPaintAt = Number.POSITIVE_INFINITY
    await page.exposeFunction('__markFirstPaint', () => {
      firstPaintAt = Date.now()
    })
    await page.addInitScript(() => {
      new PerformanceObserver((list) => {
        for (const entry of list.getEntries()) {
          if (entry.name === 'first-contentful-paint') window.__markFirstPaint()
        }
      }).observe({ type: 'paint', buffered: true })
    })
    const started = Date.now()
    page.on('response', (response) => {
      const url = response.url()
      if (!url.endsWith('.js')) return
      if (Date.now() > firstPaintAt) return
      eager.add(path.basename(new URL(url).pathname))
    })
    await page.goto(`http://127.0.0.1:${port}/`, { waitUntil: 'domcontentloaded' })
    await page
      .waitForFunction(() => performance.getEntriesByName('first-contentful-paint').length > 0, null, {
        timeout: 15000,
      })
      .catch(() => {})
    // Let in-flight scripts that prerendered the first screen land.
    await page.waitForTimeout(Math.max(0, 3000 - (Date.now() - started)))
    return { files: [...eager], source: 'browser (before first contentful paint)' }
  } finally {
    await browser.close()
    server.close()
  }
}

